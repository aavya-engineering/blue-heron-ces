import * as path from 'path';
import { ExecutionReport } from '../core/StamperEngine.js';
import { StamperConfig } from '../config/StamperConfig.js';
import { BHD_PROVENANCE } from '../config/provenance.js';
import { writeJsonArtifact, writeTextArtifact } from 'ces-shared/persistence/files';

export class ExecutionReporter {
  private config: StamperConfig;

  constructor(config: StamperConfig) {
    this.config = config;
  }

  generateJsonReport(report: ExecutionReport): string {
    return JSON.stringify({ provenance: BHD_PROVENANCE, ...report }, null, 2);
  }

  generateMarkdownReport(report: ExecutionReport): string {
    const lines: string[] = [];

    lines.push(`# Stamper Execution Report`);
    lines.push('');
    lines.push(`> Generated by: ${BHD_PROVENANCE.generatedBy} | On behalf of: ${BHD_PROVENANCE.onBehalfOf} | License: ${BHD_PROVENANCE.licenseType}`);
    lines.push('');
    lines.push(`**Plan ID:** ${report.plan_id}`);
    lines.push(`**Status:** ${report.status.toUpperCase()}`);
    lines.push(`**Started:** ${report.started_at}`);
    lines.push(`**Completed:** ${report.completed_at}`);
    lines.push(`**Duration:** ${this.formatDuration(report.duration_ms)}`);
    lines.push('');

    lines.push(`## Summary`);
    lines.push('');
    lines.push(`| Metric | Count |`);
    lines.push(`|--------|-------|`);
    lines.push(`| Total Tasks | ${report.summary.total_tasks} |`);
    lines.push(`| Completed (Stamper) | ${report.summary.completed} |`);
    lines.push(`| Accomplished (Operator) | ${report.summary.accomplished} |`);
    lines.push(`| Failed | ${report.summary.failed} |`);
    lines.push(`| Skipped | ${report.summary.skipped} |`);
    lines.push(`| Evidence Collected | ${report.evidence_collected} |`);
    lines.push('');

    if (report.failed_tasks.length > 0) {
      lines.push(`## Failed Tasks`);
      lines.push('');
      for (const failure of report.failed_tasks) {
        lines.push(`### ${failure.task_id}`);
        lines.push('');
        lines.push(`**Error:** ${failure.error}`);
        lines.push('');
        lines.push(`**Rollback Action:** ${failure.rollback_action}`);
        lines.push('');
      }
    }

    // Per-control results table (110 controls)
    if (report.controlResults && report.controlResults.length > 0) {
      lines.push(`## Control Results`);
      lines.push('');
      lines.push(`| Family/ID | Name | Directive | Result |`);
      lines.push(`|-----------|------|-----------|--------|`);
      for (const cr of report.controlResults) {
        lines.push(`| ${cr.controlId} | ${cr.name} | ${cr.directive} | ${cr.verdict} |`);
      }
      lines.push('');
    }

    // Directive breakdown: Documented Absences and Documented Prohibitions
    const reportAny = report as any;
    const absenceControls: Array<{ controlId: string; justification: string }> = reportAny.directive_absences || [];
    const prohibitionControls: Array<{ controlId: string; justification: string; enforcementStatus: string }> = reportAny.directive_prohibitions || [];

    if (absenceControls.length > 0) {
      lines.push(`## Documented Absences (N/A)`);
      lines.push('');
      lines.push(`| Control ID | Justification |`);
      lines.push(`|-----------|---------------|`);
      for (const ac of absenceControls) {
        lines.push(`| ${ac.controlId} | ${ac.justification} |`);
      }
      lines.push('');
    }

    if (prohibitionControls.length > 0) {
      lines.push(`## Documented Prohibitions (MET/NOT MET)`);
      lines.push('');
      lines.push(`| Control ID | Justification | Enforcement Status |`);
      lines.push(`|-----------|---------------|--------------------|`);
      for (const pc of prohibitionControls) {
        lines.push(`| ${pc.controlId} | ${pc.justification} | ${pc.enforcementStatus} |`);
      }
      lines.push('');
    }

    if (report.recommendations.length > 0) {
      lines.push(`## Recommendations`);
      lines.push('');
      for (const rec of report.recommendations) {
        lines.push(`- ${rec}`);
      }
      lines.push('');
    }

    lines.push(`---`);
    lines.push(`*Generated by ${BHD_PROVENANCE.generatedBy} for ${BHD_PROVENANCE.onBehalfOf} at ${new Date().toISOString()}*`);

    return lines.join('\n');
  }

  saveReport(report: ExecutionReport, outputDir?: string): {
    jsonPath: string;
    markdownPath: string;
  } {
    const reportDir = outputDir || path.join(this.config.stateDir, report.plan_id);

    const timestamp = new Date().toISOString().replace(/:/g, '-').split('.')[0];
    const jsonPath = path.join(reportDir, `execution-report-${timestamp}.json`);
    const markdownPath = path.join(reportDir, `execution-report-${timestamp}.md`);

    // Same content as generateJsonReport (JSON.stringify(x, null, 2)); routed through the
    // sanctioned file-artifact writer (G2). generateJsonReport stays for printReport/callers.
    writeJsonArtifact(jsonPath, { provenance: BHD_PROVENANCE, ...report });
    writeTextArtifact(markdownPath, this.generateMarkdownReport(report));

    return {
      jsonPath,
      markdownPath
    };
  }

  printReport(report: ExecutionReport): void {
    console.log('\n' + '='.repeat(80));
    console.log('EXECUTION REPORT');
    console.log('='.repeat(80));
    console.log(`Plan: ${report.plan_id}`);
    console.log(`Status: ${report.status.toUpperCase()}`);
    console.log(`Duration: ${this.formatDuration(report.duration_ms)}`);
    console.log('');
    console.log('Summary:');
    console.log(`  Total Tasks: ${report.summary.total_tasks}`);
    console.log(`  Completed (Stamper): ${report.summary.completed}`);
    console.log(`  Accomplished (Operator): ${report.summary.accomplished}`);
    console.log(`  Failed: ${report.summary.failed}`);
    console.log(`  Skipped: ${report.summary.skipped}`);
    console.log(`  Evidence Collected: ${report.evidence_collected}`);
    console.log('');

    if (report.failed_tasks.length > 0) {
      console.log('Failed Tasks:');
      for (const failure of report.failed_tasks) {
        console.log(`  - ${failure.task_id}: ${failure.error}`);
      }
      console.log('');
    }

    if (report.recommendations.length > 0) {
      console.log('Recommendations:');
      for (const rec of report.recommendations) {
        console.log(`  - ${rec}`);
      }
      console.log('');
    }

    console.log('Built by Blue Heron Defense, LLC for ValorForge Solutions');
    console.log('='.repeat(80));
    console.log('');
  }

  private formatDuration(ms: number): string {
    const seconds = Math.floor(ms / 1000);
    const minutes = Math.floor(seconds / 60);
    const hours = Math.floor(minutes / 60);

    if (hours > 0) {
      return `${hours}h ${minutes % 60}m ${seconds % 60}s`;
    } else if (minutes > 0) {
      return `${minutes}m ${seconds % 60}s`;
    } else {
      return `${seconds}s`;
    }
  }
}
