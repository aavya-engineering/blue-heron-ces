// W4-ST2 — consume Muster's Infra Manifest end to end (gate: ces-muster W4-MU1, 299cac2).
//
// Inputs, none hand-supplied:
//   - ces-muster's committed goldens (read-only): manual-mission-plan.json,
//     tenant-manifest.json and infrastructure-manifest.json (W4-MU1).
//   - the sim tenant record, machine-generated by tenant-stacksim's own
//     buildSimTenantConfig() and registered as kind:'sim' in a temp ces-tenant
//     registry (CES_TENANT_ROOT) — the same record `stacksim init-tenant` emits.
// The real CLI `translate --tenant` picks the Infra Manifest up by name next to the
// Tenant Manifest (Muster's push writes infrastructure-manifest-<slug>-<ts>.json) and the
// translator merges its stamper_variable_map. The executable plan then runs as a dry run
// through the production execute route against an in-process stacksim.
//
// MS-5 (FC-ST-2, 2026-09-28): the sim tenant record now supplies the three variables that
// used to have no producer anywhere in the ecosystem (approverUPN, initialPassword,
// touFileBase64) — tenant-stacksim `ebcaa2a` (REQ-tenant-stacksim-sim-tenant-secret-variables,
// replied "Done" in ../tenant-stacksim/docs/requirements/REPLIES-2026-09-27.md). Criterion
// (0 unresolved-variable warnings) is now met and is asserted as a real (non-`.failing`) test.
// The password is a fixed, obviously-fake sim literal (`Sim-Only-Initial-Pa55!-NOT-A-SECRET`)
// -- never a real secret -- and this file also proves it is never written into a compliance
// evidence file (only into the plan/tenant variables, where it must live to be usable).
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import http from 'http';
import express from 'express';
import { spawnSync } from 'child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');

const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'w4-st2-'));
process.env.CES_PIPELINE_ROOT = tmpRoot;
delete process.env.CES_MUSTER_API_URL;

import { createExecuteRouter } from '../../src/server/routes/execute.routes';
import { UNRESOLVED_VARIABLE_PREFIX, UNRESOLVED_RUNTIME_VARIABLE_PREFIX } from '../../src/translators/PlanTranslator';
import { DEFAULT_SIM_TENANT_SLUG } from '../../src/tenant/stamperTenants';
import { startStacksim, applyEnv, STACKSIM_ROOT, type StacksimHarness } from '../helpers/stacksimHarness';
import { buildStructuredEvidence } from '../../src/utils/structuredEvidence';

/** MS-5: the three variables only the sim tenant record produces (Stamper's own default has none). */
const MS5_VARS = ['approverUPN', 'initialPassword', 'touFileBase64'];

const readJson = (p: string) => JSON.parse(fs.readFileSync(p, 'utf-8'));
/** The committed golden on ces-muster main (its own git repo) — not a possibly-dirty working tree. */
const committedGolden = (name: string): string => {
  const r = spawnSync('git', ['-C', path.resolve(ROOT, '..', 'ces-muster'), 'show', `main:src/features/plan/__fixtures__/${name}`], { encoding: 'utf-8', maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`git show ces-muster main:${name} failed: ${r.stderr}`);
  return r.stdout;
};
/** Resolved at execution from the tenant record's credentials (ExecutionContext.loadClientConfig); a dry run loads none. */
const CREDENTIAL_VARS = ['tenantId', 'appId', 'certThumbprint', 'certPath'];
const unresolvedVars = (warnings: string[], prefix: string) =>
  [...new Set(warnings.filter((w) => w.startsWith(prefix)).map((w) => w.slice(prefix.length).trim().split(' ')[0]))].sort();

function getSse(url: string): Promise<any[]> {
  return new Promise((resolve, reject) => {
    const events: any[] = [];
    http.get(url, (res) => {
      let buf = '';
      res.setEncoding('utf-8');
      res.on('data', (c: string) => {
        buf += c;
        let i: number;
        while ((i = buf.indexOf('\n\n')) >= 0) {
          for (const line of buf.slice(0, i).split('\n')) if (line.startsWith('data: ')) events.push(JSON.parse(line.slice(6)));
          buf = buf.slice(i + 2);
        }
      });
      res.on('end', () => resolve(events));
    }).on('error', reject);
  });
}

describe('W4-ST2 Muster plan + Infra Manifest -> translate -> stacksim dry run', () => {
  const tenantRoot = path.join(tmpRoot, 'tenant-registry');
  const inDir = path.join(tmpRoot, 'muster-push');
  const outPath = path.join(tmpRoot, 'executable-plan.json');
  let cli: ReturnType<typeof spawnSync>;
  let plan: any;
  let warnings: string[] = [];
  let infra: any;
  let record: any;

  beforeAll(async () => {
    // Muster's push layout: TM and IM side by side (plan.ts writes infrastructure-manifest-<slug>-<ts>.json).
    fs.mkdirSync(inDir, { recursive: true });
    fs.writeFileSync(path.join(inDir, 'manual-mission-plan-golden.json'), committedGolden('manual-mission-plan.json'));
    fs.writeFileSync(path.join(inDir, 'tenant-manifest-golden.json'), committedGolden('tenant-manifest.json'));
    fs.writeFileSync(path.join(inDir, 'infrastructure-manifest-golden.json'), committedGolden('infrastructure-manifest.json'));
    infra = readJson(path.join(inDir, 'infrastructure-manifest-golden.json'));

    // Sim tenant record generated by tenant-stacksim itself, registered kind:'sim'.
    const { buildSimTenantConfig } = await import(pathToFileURL(path.join(STACKSIM_ROOT, 'dist', 'src', 'config', 'SimTenantConfig.js')).href);
    record = { ...buildSimTenantConfig({ slug: DEFAULT_SIM_TENANT_SLUG, tenantStance: 'm365_azure' }), kind: 'sim' };
    fs.mkdirSync(path.join(tenantRoot, 'sim'), { recursive: true });
    fs.writeFileSync(path.join(tenantRoot, 'sim', `${DEFAULT_SIM_TENANT_SLUG}.json`), JSON.stringify(record, null, 2));

    cli = spawnSync(
      `npx tsx src/cli/index.ts translate "${path.join(inDir, 'manual-mission-plan-golden.json')}" -m "${path.join(inDir, 'tenant-manifest-golden.json')}" --tenant ${DEFAULT_SIM_TENANT_SLUG} -o "${outPath}"`,
      { cwd: ROOT, env: { ...process.env, CES_PIPELINE_ROOT: tmpRoot, CES_TENANT_ROOT: tenantRoot }, encoding: 'utf-8', shell: true, timeout: 180_000, input: '' },
    );
    if (fs.existsSync(outPath)) plan = readJson(outPath);
    warnings = String(cli.stdout ?? '').split(/\r?\n/).filter((l) => l.startsWith('  ! ')).map((l) => l.slice(4));
  }, 240_000);

  afterAll(() => {
    try { fs.rmSync(tmpRoot, { recursive: true, force: true }); } catch { /* ces.db handle on Windows */ }
  });

  it('the CLI translates with the Infra Manifest picked up next to the Tenant Manifest and merged', () => {
    expect(cli.status).toBe(0);
    expect(cli.stdout).toContain(`Infra:    ${path.join(inDir, 'infrastructure-manifest-golden.json')}`);
    expect(plan.variables._infra_manifest_source).toBe(path.join(inDir, 'infrastructure-manifest-golden.json'));

    // W4-ST4 follow-up: Muster's golden is on the canonical ces-shared 2.5.0 key (5dad046); the
    // deprecated `infrastructure_manifest` key must not come back (REQ-ces-stamper-infra-golden-canonical-key).
    expect(infra.infrastructure_manifest).toBeUndefined();
    const vm = infra.infrastructure.stamper_variable_map;
    // Only the Infra Manifest provides this one (not the Tenant Manifest, not the sim record).
    expect(plan.variables.eoAppDisplayName).toBe(vm.eoAppDisplayName);
    // Lowest precedence: the tenant record's real subscription wins; the IM's value is a generated placeholder anyway.
    expect(vm.subscriptionId).toMatch(/^sub_[a-z0-9]{8,}_[a-z0-9]{7,}$/);
    expect(plan.variables.subscriptionId).toBe(`sim-sub-${DEFAULT_SIM_TENANT_SLUG}`);
    expect(warnings).toContain(`INFRA_MANIFEST: skipped generated placeholder for "subscriptionId" (${vm.subscriptionId})`);
    // Variables the plan's sub-commands need that come from the IM are all present.
    for (const k of ['lawWorkspaceName', 'resourceGroup', 'eoAppDisplayName']) expect(plan.variables[k]).toBeTruthy();
  });

  it('MS-5: the sim tenant record\'s approverUPN/initialPassword/touFileBase64 reach the Executable Plan variables', () => {
    // Production merge path: PlanTranslator gap-fills plan.variables from clientConfig.resources
    // via VARIABLE_MAPPING (src/shared/variable-map.ts) -- asserted against the sim record itself,
    // not a hard-coded literal, so this fails if tenant-stacksim ever changes its sim values.
    expect(plan.variables.approverUPN).toBe(record.resources.approver_upn);
    expect(plan.variables.initialPassword).toBe(record.resources.initial_password);
    expect(plan.variables.touFileBase64).toBe(record.resources.tou_file_base64);
    expect(record.resources.approver_upn).toBeTruthy();
    expect(record.resources.initial_password).toBeTruthy();
    expect(record.resources.tou_file_base64).toBeTruthy();
    // None of the three are reported as unresolved any more.
    for (const v of MS5_VARS) expect(unresolvedVars(warnings, UNRESOLVED_VARIABLE_PREFIX)).not.toContain(v);
    // Runtime (capture-produced) variables are a separate concern (not this REQ). breakGlassUserId
    // is also now sim-supplied (tenant-stacksim m365_azure resources.break_glass_user_id, same
    // batch as MS-5's three, but not one of them) -- only baselineTemplateId remains unproduced.
    expect(unresolvedVars(warnings, UNRESOLVED_RUNTIME_VARIABLE_PREFIX)).toEqual(['baselineTemplateId']);
  });

  it('W4-ST2 criterion: 0 unresolved-variable warnings (REQ-tenant-stacksim-sim-tenant-secret-variables landed, ebcaa2a)', () => {
    expect(unresolvedVars(warnings, UNRESOLVED_VARIABLE_PREFIX)).toEqual([]);
  });

  describe('stacksim dry run of the translated plan', () => {
    let sim: StacksimHarness;
    let restoreEnv: () => void;
    let server: http.Server;
    let baseUrl: string;
    let events: any[];

    beforeAll(async () => {
      sim = await startStacksim(DEFAULT_SIM_TENANT_SLUG);
      restoreEnv = applyEnv(sim.shadowEnv);
      const app = express();
      app.use(express.json());
      app.use(createExecuteRouter(new Map(), () => false, () => undefined));
      await new Promise<void>((r) => { server = app.listen(0, '127.0.0.1', () => { baseUrl = `http://127.0.0.1:${(server.address() as any).port}`; r(); }); });
    }, 60_000);

    afterAll(async () => {
      await new Promise<void>((r) => server?.close(() => r()));
      restoreEnv?.();
      await sim?.stop();
    });

    it('runs clean: every required variable outside the residual set is resolved in the emitted commands', async () => {
      const ledgerBefore = (await sim.ledgerEntries()).length;
      const qs = new URLSearchParams({ plan: outPath, tenant: DEFAULT_SIM_TENANT_SLUG, dryRun: 'true', mode: 'auto', uploadToBlob: 'false' });
      events = await getSse(`${baseUrl}/api/execute?${qs}`);

      expect(events.filter((e) => e.type === 'error')).toEqual([]);
      expect(events[events.length - 1].type).toBe('done');
      expect(events.map((e) => e.type)).not.toContain('connection_log');

      const subs = events.filter((e) => e.type === 'sub_command');
      expect(subs.length).toBeGreaterThan(0);
      const unresolvedInRun = new Set<string>();
      for (const s of subs) {
        for (const v of s.registry.variables_required as string[]) {
          if (new RegExp(`(?<![$\\w])\\{${v}\\}`).test(s.command)) unresolvedInRun.add(v);
        }
      }
      // Only tenant credentials (which a dry run never loads) can remain as a literal
      // {placeholder} in the dry run -- MS5_VARS now resolve like everything else.
      expect([...unresolvedInRun].filter((v) => !MS5_VARS.includes(v) && !CREDENTIAL_VARS.includes(v))).toEqual([]);
      expect([...unresolvedInRun].filter((v) => MS5_VARS.includes(v))).toEqual([]);

      const summary = events.find((e) => e.type === 'summary');
      const failed = events.filter((e) => e.type === 'task_result' && e.status === 'fail');
      for (const f of failed) expect(f.taskId).toMatch(/^renderable-/);
      expect(summary.fail).toBe(failed.length);

      expect((await sim.ledgerEntries()).length).toBe(ledgerBefore);
    }, 180_000);

    it('secrets: initialPassword never resolves into the persisted compliance evidence record for AC.L2-3.1.6', () => {
      // The dry run's own sub_command event confirms the resolved command carries the real
      // password (that event is UI display only -- ExecutionContext.ts's own behavior, not
      // evidence). Find it to prove this test uses the REAL registry template, not a hand-typed one.
      const adminAcctEvent = events.find((e) => e.type === 'sub_command' && e.subId === 'AC.L2-3.1.6.admin-account');
      expect(adminAcctEvent).toBeTruthy();
      expect(adminAcctEvent.command).toContain(record.resources.initial_password);
      const setCommandTemplate: string = adminAcctEvent.registry.set_command_template;
      expect(setCommandTemplate).toContain('{initialPassword}');

      // Production code path: buildStructuredEvidence (src/utils/structuredEvidence.ts) is what
      // every evidence JSON file on disk is built from. Call it directly with the real template
      // and the real resolved plan.variables (which does carry the live password value) and prove
      // the persisted record's commandExecuted stays on the unresolved template -- the password
      // never lands in the written evidence, only in the in-memory variables it has to live in.
      const subCommand = { id: 'AC.L2-3.1.6.admin-account', label: 'Create Dedicated Admin Account', set_command: setCommandTemplate } as any;
      const task = { controls: ['AC.L2-3.1.6'] } as any;
      const evidence = buildStructuredEvidence('', 0, '', null, subCommand, task, plan.variables);
      expect(evidence.metadata.commandExecuted).toBe(setCommandTemplate);
      expect(evidence.metadata.commandExecuted).not.toContain(record.resources.initial_password);
      expect(JSON.stringify(evidence)).not.toContain(record.resources.initial_password);
    });
  });
});
