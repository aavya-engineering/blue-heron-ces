import { useMemo, useEffect, useState } from 'react';
import { dbHelpers } from '@/shared/db/schema';
import { makeCesTuple } from '@/shared/identity/cesTuple';
import { useAppStore } from '@/shared/stores/appStore';
import type { RRActivity } from '../types';

/**
 * Load RR Question Set from database (generated by SIT)
 */
export function useRRTQuestions() {
  const { currentCustomerId, selectedBaselineId } = useAppStore();
  const [questionSet, setQuestionSet] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!currentCustomerId) {
      setError('No customer selected');
      setLoading(false);
      return;
    }

    const loadQuestionSet = async () => {
      try {
        setLoading(true);
        setError(null);

        // Get latest baseline for customer
        const baseline = selectedBaselineId
          ? await dbHelpers.getBaselineById(
              selectedBaselineId,
              makeCesTuple(currentCustomerId, selectedBaselineId),
            )
          : await dbHelpers.getLatestBaselineByCustomer(currentCustomerId);
        if (!baseline) {
          setError('No SI Baseline found. Please complete SIT first.');
          setLoading(false);
          return;
        }

        if (baseline.customerId !== currentCustomerId) {
          setError('Selected baseline does not match the active customer.');
          setLoading(false);
          return;
        }

        // Get question set for baseline
        const qSet = await dbHelpers.getQuestionSetByBaseline(baseline.id!);
        if (!qSet) {
          setError('No RR Question Set found. Please generate it from SIT.');
          setLoading(false);
          return;
        }

        setQuestionSet(qSet.data);
        setLoading(false);
      } catch (err) {
        console.error('Error loading question set:', err);
        setError(err instanceof Error ? err.message : 'Failed to load question set');
        setLoading(false);
      }
    };

    loadQuestionSet();
  }, [currentCustomerId, selectedBaselineId]);

  const activities = useMemo<RRActivity[]>(() => {
    if (!questionSet?.ces) return [];

    // New schema: flat questions array with source_activity_id
    if (questionSet.ces.questions && Array.isArray(questionSet.ces.questions)) {
      const actMap = new Map<string, RRActivity>();
      for (const q of questionSet.ces.questions) {
        const actId = q.source_activity_id || 'default';
        if (!actMap.has(actId)) {
          actMap.set(actId, {
            activity_id: actId,
            activity_name: actId.replace(/_/g, ' '),
            questions: [],
          });
        }
        // Pass through ALL question data for rich UI display
        actMap.get(actId)!.questions.push({
          question_id: q.question_id,
          question_text: q.prompt || q.question_text || q.name || '',
          prompt: q.prompt,
          name: q.name,
          description: q.description,
          answer_type: q.answer_type === 'yes_no' ? 'boolean' : q.answer_type,
          enum_values: q.enum_values,
          mapped_requirements: q.mapped_requirements,
          expected_evidence: q.expected_evidence,
          expected_evidence_archetypes: q.expected_evidence?.map((e: any) => e.archetype_id),
          assessor_methods: q.assessor_methods,
          source_activity_id: actId,
          produces_rrt_fields: q.produces_rrt_fields,
          advisor_reason_rrt: q.advisor_reason_rrt,
          advisor_cmmc_impact: q.advisor_cmmc_impact,
          advisor_description: q.advisor_description,
          steps: q.steps,
          outputs: q.outputs,
          evidence_requests: q.evidence_requests,
        });
      }
      return Array.from(actMap.values());
    }

    // Legacy: activities array
    if (questionSet.ces.activities && Array.isArray(questionSet.ces.activities)) {
      return questionSet.ces.activities;
    }

    return [];
  }, [questionSet]);

  return {
    questionSet,
    activities,
    loading,
    error,
  };
}
