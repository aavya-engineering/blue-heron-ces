/**
 * FC-EO-B / EO-13 — CUI acknowledgment PDF content test.
 *
 * generateCuiAcknowledgmentPdf() puts the person/organization data into AcroForm text
 * FIELDS (form.createTextField(...).setText(...)), not drawn page text, so "parsing the
 * PDF" here means reloading the generated bytes with pdf-lib (already a runtime
 * dependency, not test-only) and reading the form field values back — the same library
 * the production code used to write them, exercised in the opposite direction.
 */
import { PDFDocument } from 'pdf-lib';
import { generateCuiAcknowledgmentPdf } from '../../../src/eo/screening/generateCuiAcknowledgmentPdf';

describe('generateCuiAcknowledgmentPdf', () => {
  it('produces a valid single-page PDF', async () => {
    const bytes = await generateCuiAcknowledgmentPdf({});
    expect(bytes.length).toBeGreaterThan(1000);
    // PDF file-header magic bytes.
    expect(Buffer.from(bytes.slice(0, 5)).toString('latin1')).toBe('%PDF-');

    const doc = await PDFDocument.load(bytes);
    expect(doc.getPageCount()).toBe(1);
  });

  it('embeds the supplied person name and organization into the correct form fields', async () => {
    const bytes = await generateCuiAcknowledgmentPdf({
      personName: 'Jordan Screenee',
      organizationName: 'acme-tenant',
    });

    const doc = await PDFDocument.load(bytes);
    const form = doc.getForm();

    expect(form.getTextField('person_name').getText()).toBe('Jordan Screenee');
    expect(form.getTextField('organization').getText()).toBe('acme-tenant');
  });

  it('leaves the name/organization fields blank when no options are given', async () => {
    const bytes = await generateCuiAcknowledgmentPdf();
    const doc = await PDFDocument.load(bytes);
    const form = doc.getForm();

    expect(form.getTextField('person_name').getText() ?? '').toBe('');
    expect(form.getTextField('organization').getText() ?? '').toBe('');
  });

  it('two different people produce two PDFs with distinct field values (no cross-contamination)', async () => {
    const bytesA = await generateCuiAcknowledgmentPdf({ personName: 'Person A', organizationName: 'tenant-a' });
    const bytesB = await generateCuiAcknowledgmentPdf({ personName: 'Person B', organizationName: 'tenant-b' });

    const formA = (await PDFDocument.load(bytesA)).getForm();
    const formB = (await PDFDocument.load(bytesB)).getForm();

    expect(formA.getTextField('person_name').getText()).toBe('Person A');
    expect(formB.getTextField('person_name').getText()).toBe('Person B');
    expect(formA.getTextField('organization').getText()).toBe('tenant-a');
    expect(formB.getTextField('organization').getText()).toBe('tenant-b');
  });

  it('has the expected acknowledgment form fields present (title/date/signature/checkbox)', async () => {
    const bytes = await generateCuiAcknowledgmentPdf({ personName: 'X', organizationName: 'Y' });
    const doc = await PDFDocument.load(bytes);
    const form = doc.getForm();
    const fieldNames = form.getFields().map(f => f.getName());

    expect(fieldNames).toEqual(expect.arrayContaining([
      'person_name', 'organization', 'title_role', 'acknowledgment_date',
      'agree_checkbox', 'signature', 'date_signed',
    ]));
  });
});
