#!/usr/bin/env node
// build-customer-records.mjs - fictional operating records for a synthetic customer (synthetic-customer
// W5 cycle 3, proposal P11 in LOG-W5c2-muster.md). Everything written is FICTIONAL.
//
//   node scripts/build-customer-records.mjs [--slug s1-mach]           (writes customers/<slug>/records/)
//   node scripts/build-customer-records.mjs [--slug s1-mach] --check   (exit 1 if records/ differs)
//
// Reads customers/<slug>/customer.json (roster, devices, roles, history_anchor) and writes one JSON record
// file per record kind plus records/catalog.json (kind, control tags, row count, date range, sha256 per
// file). Deterministic: no clock, no randomness; every date is history_anchor minus a fixed offset, so the
// same customer.json gives byte-identical files and hashes. Person names come from the roster only;
// visitors carry a reference id and an organisation, never a personal name. Every string is run through
// gen-customer.mjs's denylist (B25); a hit aborts the build. No workstation path is written anywhere.
//
// The harness (ces-tester step E8.5) uploads each catalog item to the Evidence Collector with the
// catalog's control tags; EvidenceOps fills the "records that evidence this control" narrative sentence
// and SSP appendices F / G from them. Uploads never change a status (verify V27).
//
// Facts mirrored from the simulator's seeded history (tenant-stacksim customerHistory.ts) so the records
// and the live reads agree: the training course names and completion offsets, the licensed population
// (staff minus the disabled leaver), the joiner / leaver days, the seeded incident (incident-s1-1, the
// phishing click and risky sign-in, ticket S1-IR-0007) and the in-progress incident-s1-2.
