// Gap closure NS-3 (GAP-CLOSURE-PLAN.md section 4, V81): the customer's records also reach EO's own stores (personnel,
// screening state, training completions, risk register, offboarding wizard). Pure: the harness (ces-tester
// src/flow/eo-records.ts) posts these and verify V81 recomputes the same expectations from the same files.
// Policies: the customer files hold no policy documents, so none is posted (see NS3_POLICY_NOTE).
export const EO_POSTS_SCHEMA = 'ces-eo-record-posts/1';
export const NS3_POLICY_NOTE = 'not posted: the customer files hold no policy documents (no policy record kind in customers/<slug>/records); Muster\'s pushed policy envelopes reach EO through FLOW-3';
export const EO_TRAINING_FILES = ['training-awareness.json', 'training-insider-threat.json', 'training-role-based.json', 'training-incident-response.json'];
const NIST_LEVEL = { 'very high': 'very_high', high: 'high', medium: 'moderate', moderate: 'moderate', low: 'low', 'very low': 'very_low' };
const NIST_LIKELIHOOD = { 'almost certain': 'very_high', 'very likely': 'very_high', likely: 'high', possible: 'moderate', unlikely: 'low', rare: 'very_low', 'very unlikely': 'very_low' };
const threatSourceOf = (threat) => (/\b(fire|flood|power|storm|weather)\b/i.test(threat) ? 'environmental'
  : /\b(delayed|lost|error|mistake|accident)\b/i.test(threat) ? 'non_adversarial' : 'adversarial');
const plusYear = (d) => { const t = new Date(`${d}T00:00:00Z`); t.setUTCFullYear(t.getUTCFullYear() + 1); return t.toISOString().slice(0, 10); };

/**
 * One customer's records (files: record file name -> parsed record) as EO request bodies, in posting order:
 * personnel (screening and lifecycle people, e-mail = the account UPN), their screening state, training completions,
 * risk register entries, offboarding runs (a leaver whose termination rows are all "done" is completed; one with an
 * open row is only started). Returns null when the files hold no personnel screening or lifecycle record.
 */
export function eoRecordPosts(customer, files) {
  const screening = files['personnel-screening.json']?.rows ?? [];
  const lifecycle = files['personnel-lifecycle.json']?.rows ?? [];
  if (!screening.length && !lifecycle.length) return null;
  const accounts = new Map((customer.accounts ?? []).map((a) => [a.person_id, a]));
  const ids = [...new Set([...screening, ...lifecycle].map((r) => r.person_id))];
  const unresolved = [];
  const personnel = [];
  for (const pid of ids) {
    const acct = accounts.get(pid);
    const sr = screening.find((r) => r.person_id === pid);
    if (!acct?.upn) { unresolved.push(pid); continue; }
    personnel.push({
      person_id: pid,
      body: { displayName: acct.display_name ?? sr?.name, email: acct.upn, role: acct.job_title ?? sr?.job_title ?? 'staff', ...(acct.object_id ? { entraObjectId: acct.object_id } : {}) },
      screening: sr ? { screeningState: sr.result === 'cleared' ? 'cleared' : 'in-progress', lastScreenedDate: sr.date } : null,
    });
  }
  const emailOf = new Map(personnel.map((p) => [p.person_id, p.body.email]));
  const training = [];
  for (const f of EO_TRAINING_FILES) {
    for (const r of files[f]?.rows ?? []) {
      if (r.status !== 'completed') continue;
      if (!emailOf.has(r.person_id)) { unresolved.push(`${f}:${r.person_id}`); continue; }
      training.push({ person_id: r.person_id, email: emailOf.get(r.person_id), file: f, body: { courseId: r.course, completedDate: r.date } });
    }
  }
  const risks = (files['risk-assessment.json']?.rows ?? []).map((r) => ({
    risk_id: r.risk_id,
    body: {
      threatSource: threatSourceOf(r.threat),
      threatEvent: r.threat,
      vulnerability: { type: 'organizational', description: r.threat, externalReferenceId: r.risk_id },
      ...(NIST_LIKELIHOOD[String(r.likelihood).toLowerCase()] ? { likelihood: NIST_LIKELIHOOD[String(r.likelihood).toLowerCase()] } : {}),
      ...(NIST_LEVEL[String(r.impact).toLowerCase()] ? { impact: NIST_LEVEL[String(r.impact).toLowerCase()] } : {}),
      ...(NIST_LEVEL[String(r.rating).toLowerCase()] ? { compositeRisk: NIST_LEVEL[String(r.rating).toLowerCase()] } : {}),
      treatmentRecommendation: 'mitigate',
      treatmentStatus: 'in_progress',
      ...(r.treatment ? { treatmentReference: r.treatment } : {}),
      lastReviewed: r.date,
      nextReviewDue: plusYear(r.date),
      source: { type: 'manual', description: `customer risk register (risk-assessment.json) ${r.risk_id}` },
      sourceReference: r.risk_id,
      ...(r.owner ? { notes: `owner: ${r.owner}` } : {}),
    },
  }));
  const offboarding = [];
  for (const pid of [...new Set(lifecycle.filter((r) => r.event === 'termination').map((r) => r.person_id))]) {
    if (!emailOf.has(pid)) continue;
    const rows = lifecycle.filter((r) => r.event === 'termination' && r.person_id === pid);
    const complete = rows.every((r) => r.status === 'done');
    const done = rows.filter((r) => r.status === 'done');
    offboarding.push({
      person_id: pid,
      email: emailOf.get(pid),
      complete,
      attestor: (done[done.length - 1] ?? rows[0]).performed_by,
      notes: `customer termination checklist (personnel-lifecycle.json, ${rows[0].date}): ${rows.map((r) => `${r.step} [${r.status}]`).join('; ')}`,
    });
  }
  return { schema: EO_POSTS_SCHEMA, slug: customer.slug, personnel, training, risks, offboarding, policies: [], policy_note: NS3_POLICY_NOTE, unresolved };
}

/** What EO's stores should hold after the posts: personnel by e-mail with their end state, completions, risks. */
export function eoRecordExpectations(posts) {
  if (!posts) return null;
  const leaver = new Map(posts.offboarding.map((o) => [o.email, o]));
  return {
    personnel: posts.personnel.map((p) => {
      const o = leaver.get(p.body.email);
      return { email: p.body.email, displayName: p.body.displayName, screeningState: o ? (o.complete ? 'offboarded' : 'offboarding-in-progress') : (p.screening?.screeningState ?? 'unscreened'), overlay: !!o?.complete };
    }),
    training: posts.training.map((t) => ({ email: t.email, courseId: t.body.courseId, completedDate: t.body.completedDate })),
    risks: posts.risks.map((r) => ({ sourceReference: r.risk_id, threatEvent: r.body.threatEvent })),
  };
}

/** The posts for customers/<slug> under the run package, or null (no customer.json or no records catalog). */
export function loadEoRecordPosts(pkgRoot, slug) {
  const dir = path.join(pkgRoot, 'customers', slug);
  const cat = path.join(dir, 'records', 'catalog.json');
  if (!existsSync(path.join(dir, 'customer.json')) || !existsSync(cat)) return null;
  const readJ = (p) => JSON.parse(readFileSync(p, 'utf8').replace(/^﻿/, ''));
  const files = {};
  for (const item of readJ(cat).items ?? []) files[item.file] = readJ(path.join(dir, 'records', item.file));
  return eoRecordPosts(readJ(path.join(dir, 'customer.json')), files);
}

