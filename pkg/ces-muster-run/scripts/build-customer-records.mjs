// customers/<slug>/document-reviews.json (schema ces-document-reviews/1) names the artifacts E8.5 uploads with the uploader's
// principal, the per-objective reviews E8.6 posts to EO (POST /api/reviews, rule GD-b), the objectives left unreviewed and
// the V80 probe (an upload no review cites). An artifact is a records/ catalog file (bytes must hash to the catalog sha256;
// control tags, media type, role and collected_at come from the catalog) or a file under review-artifacts/ that declares
// them. The plan is checked here so a bad file fails E8.5, never a silent upload: objective ids against the 800-171A
// reference when given, reviewer != uploader != operator, every review on a control its artifact is tagged with, the probe
// artifact never reviewed and its control never reviewed.
export const REVIEWS_SCHEMA = 'ces-document-reviews/1';
export const REVIEW_PLAN_SCHEMA = 'mx-e2e/review-plan@1';

/** The E8.5 / E8.6 plan for customers/<slug>, or null when the slug has no document-reviews.json. Throws on any defect. */
export function loadDocumentReviews(pkgRoot, slug, { objectivesRef = null } = {}) {
  const dir = path.join(pkgRoot, 'customers', slug);
  const file = path.join(dir, 'document-reviews.json');
  if (!existsSync(file)) return null;
  const readJ = (p) => JSON.parse(readFileSync(p, 'utf8').replace(/^﻿/, ''));
  const doc = readJ(file);
  const fail = (m) => { throw new Error(`customers/${slug}/document-reviews.json: ${m}`); };
  if (doc.schema !== REVIEWS_SCHEMA) fail(`schema ${doc.schema} is not ${REVIEWS_SCHEMA}`);
  if (doc.slug !== slug) fail(`slug ${doc.slug} is not ${slug}`);
  const lc = (s) => String(s ?? '').trim().toLowerCase();
  const upnOk = (u) => typeof u === 'string' && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(u);
  const reviews = doc.reviews ?? [];
  if (!upnOk(doc.uploader?.upn)) fail('uploader.upn is not a UPN');
  if (!upnOk(doc.operator_upn)) fail('operator_upn is not a UPN');
  if (reviews.length) {
    if (!upnOk(doc.reviewer?.upn)) fail('reviewer.upn is not a UPN');
    if (lc(doc.reviewer.upn) === lc(doc.uploader.upn)) fail('the reviewer is the uploader (GD-b)');
    if (lc(doc.reviewer.upn) === lc(doc.operator_upn)) fail('the reviewer is the minting operator (EO refuses self_mint)');
  }
  const catPath = path.join(dir, 'records', 'catalog.json');
  const catalog = existsSync(catPath) ? readJ(catPath) : { items: [] };
  const uploads = [];
  for (const a of doc.artifacts ?? []) {
    if (!a.id || uploads.some((u) => u.id === a.id)) fail(`artifact id ${a.id} missing or repeated`);
    const rel = String(a.file ?? '');
    if (!/^(records|review-artifacts)\/[A-Za-z0-9._-]+$/.test(rel)) fail(`artifact ${a.id}: file ${rel} is not records/<f> or review-artifacts/<f>`);
    const p = path.join(dir, ...rel.split('/'));
    if (!existsSync(p)) fail(`artifact ${a.id}: ${rel} not found`);
    const bytes = readFileSync(p);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    let meta;
    if (rel.startsWith('records/')) {
      const item = (catalog.items ?? []).find((i) => i.file === rel.slice('records/'.length));
      if (!item) fail(`artifact ${a.id}: ${rel} is not in records/catalog.json`);
      if (item.sha256 !== sha256) fail(`artifact ${a.id}: ${rel} sha256 ${sha256} differs from the catalog ${item.sha256}`);
      meta = { control_ids: item.control_ids, media_type: item.media_type, submitted_by_role: item.submitted_by_role, collected_at: item.collected_at };
    } else {
      meta = { control_ids: a.control_ids, media_type: a.media_type, submitted_by_role: a.submitted_by_role, collected_at: a.collected_at };
    }
    if (!Array.isArray(meta.control_ids) || !meta.control_ids.length) fail(`artifact ${a.id}: no control_ids`);
    if (!meta.media_type || !meta.submitted_by_role) fail(`artifact ${a.id}: media_type and submitted_by_role are required`);
    uploads.push({
      id: a.id, file: rel, sha256, control_ids: [...meta.control_ids],
      body: {
        tenantSlug: slug, controlIds: [...meta.control_ids], source: 'manual_upload', filename: path.basename(rel),
        mediaType: meta.media_type, contentBase64: bytes.toString('base64'), submittedByRole: meta.submitted_by_role,
        ...(meta.collected_at ? { collectedAt: meta.collected_at } : {}),
      },
    });
  }
  const objectivesOf = new Map();
  for (const o of objectivesRef?.objectives ?? []) objectivesOf.set(o.controlId, [...(objectivesOf.get(o.controlId) ?? []), o.objectiveId]);
  const seen = new Set();
  for (const r of reviews) {
    const at = `review ${r.control_id} ${r.objective_id}`;
    const u = uploads.find((x) => x.id === r.artifact);
    if (!u) fail(`${at}: artifact ${r.artifact} is not listed`);
    if (!u.control_ids.includes(r.control_id)) fail(`${at}: artifact ${r.artifact} is not tagged ${r.control_id}`);
    if (r.verdict !== 'met' && r.verdict !== 'not_met') fail(`${at}: verdict ${r.verdict}`);
    if (typeof r.notes !== 'string' || !r.notes || !/^[\x20-\x7E]*$/.test(r.notes)) fail(`${at}: notes must be non-empty printable ASCII`);
    if (objectivesRef && !(objectivesOf.get(r.control_id) ?? []).includes(r.objective_id)) fail(`${at}: not an objective of the control`);
    if (seen.has(`${r.control_id}|${r.objective_id}`)) fail(`${at}: reviewed twice`);
    seen.add(`${r.control_id}|${r.objective_id}`);
  }
  for (const n of doc.not_reviewed ?? []) {
    if (seen.has(`${n.control_id}|${n.objective_id}`)) fail(`${n.objective_id} is both reviewed and not_reviewed`);
    if (objectivesRef && !(objectivesOf.get(n.control_id) ?? []).includes(n.objective_id)) fail(`not_reviewed ${n.objective_id}: not an objective of ${n.control_id}`);
  }
  const probe = doc.probe ?? null;
  if (!probe) fail('no probe (V80 needs an upload no review cites)');
  const pu = uploads.find((x) => x.id === probe.artifact);
  if (!pu || !pu.control_ids.includes(probe.control_id)) fail(`probe artifact ${probe.artifact} missing or not tagged ${probe.control_id}`);
  if (reviews.some((r) => r.artifact === probe.artifact || r.control_id === probe.control_id)) fail('the probe artifact or control is reviewed');
  return {
    schema: REVIEW_PLAN_SCHEMA, slug, uploader: doc.uploader, reviewer: doc.reviewer ?? null, operatorUpn: doc.operator_upn,
    uploads,
    reviews: reviews.map((r) => ({ control_id: r.control_id, objective_id: r.objective_id, artifact: r.artifact, verdict: r.verdict, notes: r.notes })),
    notReviewed: doc.not_reviewed ?? [],
    probe,
  };
}

/** Controls whose every reference objective has a met review and none a not_met one (GD-b met), and controls with a not_met review. */
export function reviewOutcome(plan, objectivesRef) {
  const objectivesOf = new Map();
  for (const o of objectivesRef?.objectives ?? []) objectivesOf.set(o.controlId, [...(objectivesOf.get(o.controlId) ?? []), o.objectiveId]);
  const controls = [...new Set(plan.reviews.map((r) => r.control_id))].sort();
  const met = [], notMet = [], partial = [];
  for (const c of controls) {
    const mine = plan.reviews.filter((r) => r.control_id === c);
    if (mine.some((r) => r.verdict === 'not_met')) notMet.push(c);
    else if ((objectivesOf.get(c) ?? []).length && (objectivesOf.get(c) ?? []).every((o) => mine.some((r) => r.objective_id === o && r.verdict === 'met'))) met.push(c);
    else partial.push(c);
  }
  return { met, notMet, partial };
}

async function denylistModule() {
  return import(pathToFileURL(path.join(PKG, 'customers', 's1-mach', 'gen-customer.mjs')).href);
}

/** Denylist hits over every record and the catalog (gen-customer.mjs's B25 denylist). */
export async function scanRecords(built, denylist) {
  const { loadDenylist, scanStrings } = await denylistModule();
  const rx = denylist ?? loadDenylist();
  const hits = [];
  for (const f of built.files) hits.push(...scanStrings(JSON.parse(f.text), rx).map((h) => `${f.file} ${h}`));
  hits.push(...scanStrings(built.catalog, rx).map((h) => `catalog.json ${h}`));
  // No workstation path may reach a record (drive letters, user profiles, UNC shares).
  const pathRx = /[A-Za-z]:[\\/]|\\\\[A-Za-z]|[\\/]Users[\\/]|[\\/]home[\\/]/;
  for (const f of built.files) if (pathRx.test(f.text)) hits.push(`${f.file}: workstation-path pattern`);
  if (pathRx.test(built.catalogText)) hits.push('catalog.json: workstation-path pattern');
  return hits;
}

