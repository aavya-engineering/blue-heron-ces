/** One record file per spec, plus the catalog (every customer's record set). */
function serialise(customer, files) {
  const orgName = customer.organization.legal_name;
  // ---------------------------------------------------------------- serialise
  const out = [];
  for (const f of files) {
    const dates = f.rows.map((r) => r.date).sort();
    const doc = {
      _fictional: FICTIONAL_NOTE,
      marker: MARKER,
      schema: RECORD_SCHEMA,
      organisation: orgName,
      record_kind: f.record_kind,
      kind_label: f.kind_label,
      title: f.title,
      kept_by: `${f.kept_by.display_name} (${f.kept_by.job_title})`,
      period: { from: dates[0], to: dates[dates.length - 1] },
      columns: f.columns,
      rows: f.rows,
    };
    const text = JSON.stringify(doc, null, 2) + '\n';
    out.push({ spec: f, doc, text, sha256: createHash('sha256').update(text, 'utf8').digest('hex'), bytes: Buffer.byteLength(text, 'utf8') });
  }
  const catalog = {
    _fictional: FICTIONAL_NOTE,
    marker: MARKER,
    schema: CATALOG_SCHEMA,
    slug: customer.slug,
    history_anchor: customer.history_anchor,
    record_schema: RECORD_SCHEMA,
    upload: 'ces-tester step E8.5 posts each item to the Evidence Collector (POST /api/ingest, source manual_upload) with control_ids as controlIds, media_type, submitted_by_role and collected_at; no form_id / emx_ids (the release-0 evidence catalog has no form for these records)',
    items: out.map(({ spec, doc, sha256, bytes }) => ({
      file: spec.file,
      record_kind: spec.record_kind,
      kind_label: spec.kind_label,
      title: spec.title,
      control_ids: spec.control_ids,
      closes: spec.closes,
      media_type: 'application/json',
      submitted_by_role: 'compliance_officer',
      collected_at: `${doc.period.to}T17:00:00.000Z`,
      rows: doc.rows.length,
      period: doc.period,
      sha256,
      size_bytes: bytes,
    })),
  };
  return { files: out.map(({ spec, text, sha256 }) => ({ file: spec.file, text, sha256 })), catalog, catalogText: JSON.stringify(catalog, null, 2) + '\n' };
}

