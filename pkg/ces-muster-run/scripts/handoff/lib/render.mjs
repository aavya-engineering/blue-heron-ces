// Renderers for the generated kit files. Output is deterministic: no timestamps, only the
// manifest's release.cut date, so check.mjs can compare a fresh render with the file on disk.

import { buildOrder } from './graph.mjs';
import { REPO_INFO, ORG_URL, COMPONENT_GLOSS, LEGEND } from './kitdata.mjs';

const GEN_NOTE = 'Generated by scripts/handoff/gen.mjs from handoff.manifest.yaml. Do not edit; edit the manifest and rerun gen.';

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const code = (v) => (v === undefined || v === null || v === '' ? '' : '`' + String(v).replace(/`/g, "'") + '`');
const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
function table(head, rows) {
  return [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n');
}
function legend(entries) {
  return ['## Legend', '', ...entries.map(([k, v]) => `- **${k}**: ${v}`)].join('\n');
}

export function runIn(component) {
  if (component.cwd) return component.cwd;
  const dir = REPO_INFO[component.repo]?.dir;
  return dir ?? `<${component.repo} root>`;
}

export function renderManifestJson(manifest) {
  return JSON.stringify(manifest, null, 2) + '\n';
}

export function renderBuildOrder(manifest) {
  const comps = manifest.components;
  const byId = new Map(comps.map((c) => [c.id, c]));
  const order = buildOrder(comps);
  const mid = (id) => id.replace(/[^A-Za-z0-9]/g, '_');
  const lines = [];
  lines.push(`# CES build order (release ${manifest.release.id})`);
  lines.push('');
  lines.push(`> ${GEN_NOTE}`);
  lines.push('');
  lines.push('Build the components in this order. Each step runs in the folder shown, relative to the workspace root (the ces-mono clone). A step may start only when every component in its "after" column has built. Build commands chain with `&&`, so run them in `cmd /c` or PowerShell 7, not Windows PowerShell 5.1.');
  lines.push('');
  lines.push(table(
    ['Step', 'Component', 'Kind', 'Run in', 'Build command', 'After'],
    order.map((id, i) => {
      const c = byId.get(id);
      return [String(i + 1), c.id, c.kind, code(runIn(c)), code(c.build), (c.deps ?? []).join(', ') || '(none)'];
    }),
  ));
  lines.push('');
  lines.push('## Unit tests, same order');
  lines.push('');
  lines.push(table(
    ['Component', 'Run in', 'Test command'],
    order.map((id) => { const c = byId.get(id); return [c.id, code(runIn(c)), code(c.test)]; }),
  ));
  lines.push('');
  lines.push('## Dependency graph');
  lines.push('');
  lines.push('An arrow points from a component to the components that build after it.');
  lines.push('');
  lines.push('```mermaid');
  lines.push('graph TD');
  for (const id of order) lines.push(`  ${mid(id)}["${id} (${byId.get(id).kind})"]`);
  for (const id of order) for (const d of byId.get(id).deps ?? []) lines.push(`  ${mid(d)} --> ${mid(id)}`);
  lines.push('```');
  lines.push('');
  lines.push(legend([
    ['After', 'the components (manifest `deps`) that must build before this one. Some are install-order dependencies: the ces-mono root `npm ci` runs in the ces-shared step, so every other ces-mono component comes after ces-shared.'],
    ['Run in', 'the folder, relative to the workspace root, where the command runs (manifest `cwd`, else the repo folder).'],
    ...LEGEND.filter(([k]) => ['workspace root'].includes(k)),
  ]));
  lines.push('');
  return lines.join('\n');
}

export function renderReadme(manifest, contracts) {
  const comps = manifest.components;
  const r = manifest.release;
  const L = [];
  L.push(`# CES build handoff kit (release ${r.id})`);
  L.push('');
  L.push(`> ${GEN_NOTE}`);
  L.push('');
  L.push(`Release **${r.id}**, cut ${r.cut}, status **${r.status}**${r.status === 'draft' ? ' (commits are the repo heads at the cut and may still move; a pinned release fixes them)' : ''}.`);
  L.push('');
  L.push('This kit lets a contractor build, run and prove CES (the BHD compliance engine) on a clean Windows machine. Build and test against the simulator (tenant-stacksim) first. Live GCC High work needs the contractor\'s own tenant or a scoped guest account. The kit is delivered through the private GitHub organization and a link, never as an emailed script or zip.');
  L.push('');
  L.push('## Files in this kit');
  L.push('');
  L.push(table(['File', 'What it is', 'Made by'], [
    ['handoff.manifest.yaml', 'Components, commits, build and test commands, ports, toolchain. The source of truth.', 'hand-written'],
    ['handoff.manifest.json', 'The same manifest as JSON, for scripts that do not parse YAML.', 'gen.mjs'],
    ['contracts.yaml', 'Versions of the files, APIs and database the components exchange, and the compatibility rule for each.', 'hand-written'],
    ['config.schema.yaml', 'Every setting the code reads: name, default, owner, scope, where it is read.', 'hand-written'],
    ['secrets.inventory.yaml', 'Every secret by name: purpose, store, who creates it, rotation. No values.', 'hand-written'],
    ['.env.example', 'Settings template made from config.schema.yaml; secrets appear as NAME= only.', 'gen.mjs'],
    ['BUILD-ORDER.md', 'The order to build in, and a dependency graph.', 'gen.mjs'],
    ['README.md', 'This page.', 'gen.mjs'],
    ['START-HERE.md, GUIDE.md', 'The page to read first, and the full step-by-step guide: what you have, setup, build, run, results, first day, live tenant.', 'hand-written'],
    ['PUNCH-LIST.md', 'Every open item, stop and decision at the cut, with owner and priority.', 'hand-written'],
    ['bootstrap.ps1', 'One entry point: checks prerequisites, clones the repos at the manifest commits (or, in the contractor monorepo, checks the folders against SOURCES.json), builds in order.', 'hand-written'],
    ['verify/', 'Smoke, acceptance and proof-round scripts (round.ps1 runs all four scenarios) and the expected results.', 'hand-written'],
    ['ACCEPTANCE.md, RUNBOOK.md, KNOWN-ISSUES.md', 'Definition of done and sign-off; how to operate; known problems.', 'hand-written'],
    ['sbom/', 'Software bill of materials per install root (scripts/handoff/sbom.mjs).', 'sbom.mjs'],
  ]));
  L.push('');
  L.push('Regenerate the generated files with `node scripts/handoff/gen.mjs` and check for drift with `node scripts/handoff/check.mjs` (exit 1 means something is out of date), both run from the run-package root (in the contractor monorepo: pkg/ces-muster-run; the scripts find the kit at the repo root).');
  L.push('');
  L.push('## Repositories');
  L.push('');
  L.push(`All repositories are in the private organization ${ORG_URL}. They must sit in one nested layout because packages link to each other with relative file: paths.`);
  L.push('');
  const repos = [...new Set(comps.map((c) => c.repo))];
  L.push(table(['Repo (manifest id)', 'GitHub repository', 'Folder in the workspace', 'Commit'], repos.map((id) => {
    const info = REPO_INFO[id] ?? {};
    const commits = [...new Set(comps.filter((c) => c.repo === id).map((c) => c.commit))];
    return [id, info.github ?? '', code(info.dir ?? ''), commits.map(code).join(', ')];
  })));
  L.push('');
  L.push('## Toolchain');
  L.push('');
  L.push(table(['Tool', 'Version', 'Why', 'Check'], manifest.toolchain.map((t) => [t.name, t.version, t.why, code(t.check)])));
  L.push('');
  L.push('## Components');
  L.push('');
  L.push(table(['Component', 'What it is', 'Kind', 'Repo', 'Path', 'Build', 'Test'], comps.map((c) => [
    c.id, COMPONENT_GLOSS[c.id] ?? c.kind, c.kind, c.repo, code(c.path), code(c.build), code(c.test),
  ])));
  L.push('');
  L.push('## Ports');
  L.push('');
  L.push('Code defaults: what each server binds when started with no flags. "0.0.0.0" means every interface; access is gated by tokens, not by the bind address.');
  L.push('');
  const ports = comps.flatMap((c) => (c.ports ?? []).map((p) => [String(p.port), c.id, p.service, p.bind, code(p.configKey)]));
  ports.sort((a, b) => Number(a[0]) - Number(b[0]));
  L.push(table(['Port', 'Component', 'Service', 'Default bind', 'Set with'], ports));
  const dup = Object.entries(ports.reduce((m, p) => ((m[p[0]] = [...(m[p[0]] ?? []), p[1]]), m), {})).filter(([, v]) => v.length > 1);
  if (dup.length) {
    L.push('');
    for (const [port, ids] of dup) L.push(`Port ${port} is the default of ${ids.join(' and ')}; start them with different ports on one machine.`);
  }
  const loop = ports.filter((p) => /^(127\.0\.0\.1|localhost|::1)$/.test(p[3]));
  if (loop.length) {
    L.push('');
    L.push(`Loopback by default: ${loop.map((p) => `${p[1]} (${p[0]})`).join(', ')}. Other machines cannot reach these until the bind address is changed.`);
  }
  L.push('');
  if (contracts) {
    L.push('## Contracts');
    L.push('');
    L.push('Full rules are in contracts.yaml.');
    L.push('');
    L.push(table(['Contract', 'Kind', 'Version', 'Producer', 'Consumers', 'Version defined at'], contracts.contracts.map((k) => [
      k.id, k.kind, k.version, k.producer, (k.consumers ?? []).join(', '), code(k.source),
    ])));
    L.push('');
  }
  L.push('## Rules that bind every build');
  L.push('');
  L.push('- Two-person approval is off by default; `CES_TWO_PERSON_APPROVAL=1` turns it on.');
  L.push('- No module is meant to be reachable only from its own machine; tokens gate access.');
  L.push('- Any action that adds a recurring cost is off by default and needs both DP-1 and DP-2.');
  L.push('- AI-assisted paths are off for live tenants.');
  L.push('- Never put a secret value, a tenant ID or a personal identity in the kit, in a .env file you share, or in a screenshot.');
  L.push('');
  L.push(legend(LEGEND));
  L.push('');
  return L.join('\n');
}

function envValue(v) {
  if (v === null || v === undefined) return '';
  const s = String(v);
  return /^[A-Za-z0-9_./:@,+-]*$/.test(s) ? s : '';
}

export function renderEnvExample(schema) {
  const L = [];
  L.push('# CES settings template. Generated by scripts/handoff/gen.mjs from config.schema.yaml; do not edit.');
  L.push('# Copy to .env and fill in. Optional settings are commented out at their default.');
  L.push('# Secrets appear as NAME= with no value: create each one as secrets.inventory.yaml describes.');
  L.push('# Never commit or share a filled-in copy.');
  const settings = [...schema.settings].sort((a, b) => {
    const ca = (a.component ?? [])[0] ?? '';
    const cb = (b.component ?? [])[0] ?? '';
    return ca === cb ? a.name.localeCompare(b.name) : ca.localeCompare(cb);
  });
  let group = null;
  for (const s of settings) {
    const g = (s.component ?? [])[0] ?? '(no component)';
    if (g !== group) {
      L.push('');
      L.push(`# ===== ${g} =====`);
      group = g;
    }
    L.push('');
    L.push(`# ${String(s.description ?? '').replace(/\r?\n/g, ' ')}`);
    const meta = [`owner ${s.owner}`, `scope ${s.scope}`, s.required ? 'required' : 'optional'];
    if ((s.component ?? []).length > 1) meta.push(`read by ${s.component.join(', ')}`);
    L.push(`# ${meta.join('; ')}`);
    if (s.secret) {
      L.push(`# Secret: see secrets.inventory.yaml (${s.name}). Never write the value here.`);
      L.push(`${s.name}=`);
      continue;
    }
    const def = s.default === null || s.default === undefined ? '' : String(s.default);
    if (def && envValue(def) !== def) L.push(`# Default: ${def.replace(/\r?\n/g, ' ')}`);
    if (s.allowed !== undefined && s.allowed !== null && String(s.allowed) !== '') L.push(`# Allowed: ${String(s.allowed).replace(/\r?\n/g, ' ')}`);
    L.push(`${s.required ? '' : '# '}${s.name}=${envValue(def)}`);
  }
  L.push('');
  L.push('# Legend: owner = who sets the value (BHD, contractor or operator); scope = where it applies');
  L.push('# (dev, sim = simulator, live = a real tenant, all); required/optional = whether the code needs it set.');
  L.push('');
  return L.join('\n');
}
