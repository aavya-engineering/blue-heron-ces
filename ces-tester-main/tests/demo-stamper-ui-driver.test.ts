/**
 * Fixtures are the REAL failed_tasks entries captured from both legs
 * (M0 GUI run and the July CLI needle run) — inlined, because `runs/` is
 * gitignored and machine-local.
 */
const GUI_FAILURE = {
  task_id: 'step_task_AC.L2-3.1.4_ms5bolpx_tou0hj7',
  error: 'Unresolved manifest variables: approverUPN. Ensure tenant manifest provides these values.',
  rollback_action: 'See execution logs for rollback guidance',
};
const CLI_FAILURE = {
  task_id: 'step_task_MP.L2-3.8.1_ms5bolq1_4hykc9t',
  error: 'MP.L2-3.8.1.cui-label: verification failed — Evidence validation failed',
  rollback_action: 'See execution logs for rollback guidance',
};

describe('extractRegistryEntryId', () => {
  it('extracts a registry entry-id from a verification error prefix', () => {
    expect(extractRegistryEntryId(CLI_FAILURE.error)).toBe('MP.L2-3.8.1.cui-label');
    expect(extractRegistryEntryId('IA.L2-3.5.9.tap-config: verification failed — x')).toBe('IA.L2-3.5.9.tap-config');
  });

  it('REFUSES the unresolved-variable class (the M0/M2 unmappable-id trap)', () => {
    expect(extractRegistryEntryId(GUI_FAILURE.error)).toBeUndefined();
    expect(extractRegistryEntryId('Unresolved runtime variables: breakGlassUserId.')).toBeUndefined();
  });

  it('refuses prose and bare control ids that are not entry-ids', () => {
    expect(extractRegistryEntryId('PowerShell injection guard: rejected')).toBeUndefined();
    expect(extractRegistryEntryId('MP.L2-3.8.1: verification failed')).toBeUndefined();
  });
});

describe('parseExecutionReport', () => {
  it('keys identity off task_id and mines the entry-id only when there is one', () => {
    const summary = parseExecutionReport({
      status: 'partial',
      summary: { total_tasks: 110, completed: 80, failed: 2 },
      failed_tasks: [GUI_FAILURE, CLI_FAILURE],
    });
    expect(summary.status).toBe('partial');
    expect(summary.totalTasks).toBe(110);
    expect(summary.completedTasks).toBe(80);
    expect(summary.failures[0]).toEqual({
      taskId: GUI_FAILURE.task_id,
      controlId: 'AC.L2-3.1.4',
      error: GUI_FAILURE.error,
    });
    expect(summary.failures[1].entryId).toBe('MP.L2-3.8.1.cui-label');
  });

  // GP-DEMO-3 M7: the unresolved-variable class carries no entry-id, and the raw
  // task id is regenerated by every translation — so identity falls back to the
  // CONTROL id, which survives a re-translation and can therefore be pinned.
  it('falls back to the control id (never a prose fragment, never the raw task id) when no entry-id exists', () => {
    const summary = parseExecutionReport({ failed_tasks: [GUI_FAILURE] });
    expect(summary.failureIds).toEqual(['AC.L2-3.1.4']);
    expect(summary.failureIds[0]).not.toContain('Unresolved');
    expect(summary.failureIds[0]).not.toContain('step_task_');
    // the raw task id is still recorded, just not used as identity
    expect(summary.failures[0].taskId).toBe('step_task_AC.L2-3.1.4_ms5bolpx_tou0hj7');
  });

  // The infra registry's second entry-id space, measured live in run m7-run1b.
  it('recognises the AZ-<AREA>-<NNN> registry entry-id space', () => {
    const summary = parseExecutionReport({
      failed_tasks: [
        { task_id: 'step_task_AU.L2-3.3.1_mtf0c5v6_u3axel2', error: 'AZ-LOG-001: verification failed — Evidence validation failed' },
        { task_id: 'step_task_SC.L2-3.13.10_mtf0c5v6_a2wrara', error: 'AZ-LOG-002a: verification failed — Evidence validation failed' },
      ],
    });
    expect(summary.failureIds).toEqual(['AZ-LOG-001', 'AZ-LOG-002a']);
  });

  it('prefers the entry-id in failureIds and de-duplicates', () => {
    const summary = parseExecutionReport({ failed_tasks: [CLI_FAILURE, CLI_FAILURE] });
    expect(summary.failureIds).toEqual(['MP.L2-3.8.1.cui-label']);
  });

  it('tolerates a report with no failures or a hostile shape', () => {
    expect(parseExecutionReport({ status: 'complete' }).failures).toEqual([]);
    expect(parseExecutionReport(null).failureIds).toEqual([]);
    expect(parseExecutionReport({ failed_tasks: [{ error: 'no task id' }] }).failures).toEqual([]);
  });
});

describe('execution report location', () => {
  it('builds the run-scoped plans dir', () => {
    expect(stamperPlansDir(path.join('C:', 'run'), 'demo-dib-small')).toBe(
      path.join('C:', 'run', 'Stamper', 'plan-data', 'demo-dib-small', 'plans'),
    );
  });

  it('picks the newest report and ignores everything else', () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'plans-'));
    fs.writeFileSync(path.join(dir, 'execution-report-2026-08-29T21-17-32.json'), '{}');
    fs.writeFileSync(path.join(dir, 'execution-report-2026-08-30T09-00-00.json'), '{}');
    fs.writeFileSync(path.join(dir, 'execution-report-2026-08-30T09-00-00.md'), 'x');
    fs.writeFileSync(path.join(dir, 'executable-plan-2026-08-30.json'), '{}');
    expect(findLatestExecutionReport(dir)).toBe(path.join(dir, 'execution-report-2026-08-30T09-00-00.json'));
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it('returns undefined for a directory that does not exist', () => {
    expect(findLatestExecutionReport(path.join(os.tmpdir(), 'no-such-plans-dir-4f2'))).toBeUndefined();
  });
});

function connectedFlowPage(): FakeUiPage {
  const page = new FakeUiPage({
    texts: {
      [STAMPER_SELECTORS.cardStatus2]: 'Pending',
      [STAMPER_SELECTORS.cardStatus3]: 'Pending',
      [STAMPER_SELECTORS.cardStatus4]: 'Locked',
    },
    classes: {
      [STAMPER_SELECTORS.card(0)]: 'workflow-card card-collapsed',
      [STAMPER_SELECTORS.card(1)]: 'workflow-card card-collapsed',
      [STAMPER_SELECTORS.card(2)]: 'workflow-card card-collapsed',
      [STAMPER_SELECTORS.card(3)]: 'workflow-card card-collapsed',
      [STAMPER_SELECTORS.card(4)]: 'workflow-card card-collapsed',
    },
    visible: new Set([STAMPER_SELECTORS.connectionGate]),
    responses: { '/api/translate': { ok: true } },
  });
  page.state.onClick[STAMPER_SELECTORS.gateAllow] = () => {
    page.state.classes[STAMPER_SELECTORS.card(0)] = 'workflow-card tenant-connected';
  };
  page.state.onClick[STAMPER_SELECTORS.assess] = () => {
    page.state.texts[STAMPER_SELECTORS.cardStatus2] = 'Assessed';
  };
  page.state.onClick[STAMPER_SELECTORS.translate] = () => {
    page.state.texts[STAMPER_SELECTORS.cardStatus3] = 'Translated';
  };
  page.state.onClick[STAMPER_SELECTORS.execute] = () => {
    page.state.texts[STAMPER_SELECTORS.cardStatus4] = 'Complete';
  };
  return page;
}

function baseContext(overrides: Partial<StamperUiDriveContext> = {}): StamperUiDriveContext {
  return {
    baseUrl: 'http://127.0.0.1:3000',
    slug: 'demo-dib-small',
    missionPlanPath: 'C:\\mp.json',
    manifestPath: 'C:\\tm.json',
    pipelineRoot: path.join(os.tmpdir(), 'no-such-pipeline-root-9c1'),
    planVariables: false,
    ...overrides,
  };
}

describe('runStamperUiFlow ordering', () => {
  it('arms the execute target to "tenant" AFTER tenant selection and BEFORE Execute', async () => {
    const page = connectedFlowPage();
    await runStamperUiFlow(page, baseContext());

    const selectedTenant = page.indexOf(`select ${STAMPER_SELECTORS.tenantSelect}=demo-dib-small`);
    const armed = page.indexOf(`select ${STAMPER_SELECTORS.execTarget}=tenant`);
    const executed = page.indexOf(`click ${STAMPER_SELECTORS.execute}`);
    expect(selectedTenant).toBeGreaterThanOrEqual(0);
    expect(armed).toBeGreaterThan(selectedTenant);
    expect(executed).toBeGreaterThan(armed);
    expect(page.state.values[STAMPER_SELECTORS.execMode]).toBe('auto');
  });

  it('REFUSES to execute when the target does not stick on "tenant" (sticky dry-run)', async () => {
    const page = connectedFlowPage();
    // Model the sibling bug: the GUI forces the value back to dryrun.
    page.state.onClick[STAMPER_SELECTORS.execTarget] = () => {
      page.state.values[STAMPER_SELECTORS.execTarget] = 'dryrun';
    };
    await expect(runStamperUiFlow(page, baseContext())).rejects.toThrow(/did not stick on "tenant"/);
    expect(page.indexOf(`click ${STAMPER_SELECTORS.execute}`)).toBe(-1);
  });

  it('walks connect -> paths -> assess -> translate -> execute in order', async () => {
    const page = connectedFlowPage();
    await runStamperUiFlow(page, baseContext());
    const order = [
      page.indexOf(`click ${STAMPER_SELECTORS.gateAllow}`),
      page.indexOf(`fill ${STAMPER_SELECTORS.missionPlanPath}`),
      page.indexOf(`click ${STAMPER_SELECTORS.assess}`),
      page.indexOf(`click ${STAMPER_SELECTORS.translate}`),
      page.indexOf(`click ${STAMPER_SELECTORS.execute}`),
    ];
    expect(order.every((i) => i >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  it('seeds the variable store between Assess and Translate', async () => {
    const page = connectedFlowPage();
    const seen: string[] = [];
    const result = await runStamperUiFlow(
      page,
      baseContext({
        planVariables: { approverUPN: 'a@b.us' },
        seedVariables: async (opts) => {
          seen.push(`seed:${opts.slug}:${Object.keys(opts.seed).join(',')}`);
          page.actions.push('seedVariables');
          return { route: 'api', added: ['approverUPN'], kept: [], total: 1 };
        },
      }),
    );
    expect(seen).toEqual(['seed:demo-dib-small:approverUPN']);
    expect(page.indexOf('seedVariables')).toBeGreaterThan(page.indexOf(`click ${STAMPER_SELECTORS.assess}`));
    expect(page.indexOf('seedVariables')).toBeLessThan(page.indexOf(`click ${STAMPER_SELECTORS.translate}`));
    expect(result.variableSeed?.added).toEqual(['approverUPN']);
  });

  it('fails the beat when Connect leaves error rows in the log', async () => {
    const page = connectedFlowPage();
    page.state.counts[STAMPER_SELECTORS.connectErrorRows] = 2;
    await expect(runStamperUiFlow(page, baseContext())).rejects.toThrow(/2 error row/);
  });

  it('fails honestly when Assess reports an error state', async () => {
    const page = connectedFlowPage();
    page.state.onClick[STAMPER_SELECTORS.assess] = () => {
      page.state.texts[STAMPER_SELECTORS.cardStatus2] = 'Error';
    };
    await expect(runStamperUiFlow(page, baseContext({ assessTimeoutMs: 50 }))).rejects.toThrow(/failure state/);
  });

  it('accepts a non-Complete terminal badge and still judges the artifact', async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pipeline-'));
    const plansDir = stamperPlansDir(dir, 'demo-dib-small');
    fs.mkdirSync(plansDir, { recursive: true });
    fs.writeFileSync(
      path.join(plansDir, 'execution-report-2026-08-29T21-17-32.json'),
      JSON.stringify({ status: 'partial', summary: { total_tasks: 110, completed: 80 }, failed_tasks: [CLI_FAILURE] }),
    );

    const page = connectedFlowPage();
    page.state.onClick[STAMPER_SELECTORS.execute] = () => {
      page.state.texts[STAMPER_SELECTORS.cardStatus4] = 'Error';
    };
    const result = await runStamperUiFlow(page, baseContext({ pipelineRoot: dir }));

    expect(result.executeBadge).toBe('Error');
    expect(result.report?.status).toBe('partial');
    expect(result.report?.failureIds).toEqual(['MP.L2-3.8.1.cui-label']);
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it('reports no artifact rather than inventing one when no report exists', async () => {
    const page = connectedFlowPage();
    const result = await runStamperUiFlow(page, baseContext());
    expect(result.reportPath).toBeUndefined();
    expect(result.report).toBeUndefined();
    expect(result.executeBadge).toBe('Complete');
  });
});

