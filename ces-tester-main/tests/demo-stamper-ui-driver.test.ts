describe('runStamperUiFlow executePeekMs (start → confirm running → cut away)', () => {
  it('clicks Execute, confirms running, HALTS it, and returns without awaiting terminal', async () => {
    const page = connectedFlowPage();
    // Model a run that STARTS and stays running — it never reaches a terminal
    // badge, so a full flow would hang here; the peek halts and returns anyway.
    page.state.onClick[STAMPER_SELECTORS.execute] = () => {
      page.state.texts[STAMPER_SELECTORS.cardStatus4] = 'Executing...';
    };
    const result = await runStamperUiFlow(page, baseContext({ executePeekMs: 5 }));
    expect(result.executeHalted).toBe(true);
    expect(result.executeLeftRunning).toBe(false);
    expect(result.executeBadge).toBe('Executing...');
    expect(result.report).toBeUndefined();
    expect(result.reportPath).toBeUndefined();
    // It clicked Execute, then clicked the Halt button after the peek window.
    expect(page.indexOf(`click ${STAMPER_SELECTORS.execute}`)).toBeGreaterThanOrEqual(0);
    expect(page.indexOf(`click ${STAMPER_SELECTORS.executeHalt}`)).toBeGreaterThan(
      page.indexOf(`click ${STAMPER_SELECTORS.execute}`),
    );
  });

  it('still refuses honestly when the start reports a halted/error badge', async () => {
    const page = connectedFlowPage();
    page.state.onClick[STAMPER_SELECTORS.execute] = () => {
      page.state.texts[STAMPER_SELECTORS.cardStatus4] = 'Execution halted';
    };
    await expect(runStamperUiFlow(page, baseContext({ executePeekMs: 5 }))).rejects.toThrow(/failure state/);
  });

  it('the DEFAULT (no executePeekMs) still awaits the terminal badge and judges the artifact', async () => {
    const page = connectedFlowPage();
    const result = await runStamperUiFlow(page, baseContext());
    expect(result.executeLeftRunning).toBeUndefined();
    expect(result.executeBadge).toBe('Complete');
  });
});

