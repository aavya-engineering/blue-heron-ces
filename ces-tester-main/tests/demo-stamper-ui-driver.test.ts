describe('runStamperUiFlow phases', () => {
  it('the DEFAULT is byte-identical to the flow before `phase` existed', async () => {
    // demo:e2e passes no `phase`, so this is the assertion that keeps it
    // untouched: the same actions, in the same order, with the same result.
    const implicit = connectedFlowPage();
    const explicit = connectedFlowPage();
    const a = await runStamperUiFlow(implicit, baseContext());
    const b = await runStamperUiFlow(explicit, baseContext({ phase: 'full' }));

    expect(implicit.actions).toEqual(explicit.actions);
    expect({ ...a, phase: undefined }).toEqual({ ...b, phase: undefined });
    expect(a.phase).toBe('full');
    expect(a).toMatchObject({ connected: true, assessed: true, translated: true });
  });

  it('`through-translate` stops after translate and never arms or clicks Execute', async () => {
    const page = connectedFlowPage();
    // Seeding on, because the seed is consumed AT TRANSLATE TIME — this phase
    // is the one that has to carry it.
    const seeded: string[] = [];
    const result = await runStamperUiFlow(
      page,
      baseContext({
        phase: 'through-translate',
        planVariables: { approverUPN: 'a@b.us' },
        seedVariables: async (opts) => {
          seeded.push(opts.slug);
          page.actions.push('seedVariables');
          return { path: 'x', written: {}, merged: {} } as never;
        },
      }),
    );

    expect(page.indexOf(`click ${STAMPER_SELECTORS.translate}`)).toBeGreaterThanOrEqual(0);
    expect(page.indexOf(`select ${STAMPER_SELECTORS.execTarget}=tenant`)).toBe(-1);
    expect(page.indexOf(`click ${STAMPER_SELECTORS.execute}`)).toBe(-1);

    expect(result.phase).toBe('through-translate');
    // It DID connect, assess and translate — those three are observed.
    expect(result).toMatchObject({ connected: true, assessed: true, translated: true });
    expect(result.executeBadge).toBeUndefined();
    expect(result.report).toBeUndefined();
    expect(result.translateResponse).toBeDefined();
    // ...and it seeded BEFORE translating, which is the only moment that works.
    expect(seeded).toEqual(['demo-dib-small']);
    expect(result.variableSeed).toBeDefined();
    expect(page.indexOf('seedVariables')).toBeLessThan(page.indexOf(`click ${STAMPER_SELECTORS.translate}`));
  });

  it('`execute-only` skips steps 1-6 and starts at Execute', async () => {
    const page = connectedFlowPage();
    await runStamperUiFlow(page, baseContext({ phase: 'execute-only' }));

    for (const skipped of [
      STAMPER_SELECTORS.gateAllow,
      STAMPER_SELECTORS.assess,
      STAMPER_SELECTORS.translate,
    ]) {
      expect(page.indexOf(`click ${skipped}`), skipped).toBe(-1);
    }
    expect(page.indexOf(`fill ${STAMPER_SELECTORS.missionPlanPath}`)).toBe(-1);
    // The sticky-dry-run guard still runs — it belongs to the execute step.
    expect(page.indexOf(`select ${STAMPER_SELECTORS.execTarget}=tenant`)).toBeGreaterThanOrEqual(0);
    expect(page.indexOf(`click ${STAMPER_SELECTORS.execute}`)).toBeGreaterThanOrEqual(0);
  });

  it('`execute-only` returns connected/assessed/translated as OBSERVED — all false', async () => {
    // The honesty guard: this call inherited a page that had connected,
    // assessed and translated. It did none of them, so it claims none of them.
    const page = connectedFlowPage();
    const result = await runStamperUiFlow(page, baseContext({ phase: 'execute-only' }));

    expect(result.phase).toBe('execute-only');
    expect(result).toMatchObject({ connected: false, assessed: false, translated: false });
    // What it DID do, it reports.
    expect(result.executeBadge).toBe('Complete');
  });

  it('`execute-only` does not re-seed the variable store — the seed is consumed at translate', async () => {
    const page = connectedFlowPage();
    let seeds = 0;
    const result = await runStamperUiFlow(
      page,
      baseContext({
        phase: 'execute-only',
        seedVariables: async () => {
          seeds += 1;
          return { path: 'x', written: {}, merged: {} } as never;
        },
      }),
    );
    expect(seeds).toBe(0);
    expect(result.variableSeed).toBeUndefined();
  });

  it('still REFUSES the sticky dry-run in execute-only', async () => {
    const page = connectedFlowPage();
    page.state.onClick[STAMPER_SELECTORS.execTarget] = () => {
      page.state.values[STAMPER_SELECTORS.execTarget] = 'dryrun';
    };
    await expect(runStamperUiFlow(page, baseContext({ phase: 'execute-only' }))).rejects.toThrow(
      /did not stick on "tenant"/,
    );
  });
});
