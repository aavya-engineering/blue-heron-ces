/**
 * P4.3 / V26: stacksim `coverage-ao` (AO's 95 commands), run and judged by
 * the tester.
 *
 * What the command does (tenant-stacksim src/cli/index.ts `coverage-ao`,
 * src/coverage/AoSemanticRunner.ts): it takes no scenario argument. It seeds
 * its OWN fresh m365_azure tenant with that profile's gcc-high-g5 seed set
 * (the set the `aoops-g5` scenario declares) in a temp folder, serves it on an
 * ephemeral port (not 4390), and runs every AO command's real GET, SET and
 * paired GET through the shimmed PowerShell modules. Each command is PASS,
 * HONEST-OPEN (recorded reason + REQ) or FAIL. It writes
 * coverage/ao-semantic-report.json and docs/coverage/AO-SEMANTIC-COVERAGE.md
 * inside the stacksim clone, prints
 * `stacksim coverage-ao: PASS n / HONEST-OPEN n / FAIL n (of N)`, and exits 1
 * only when FAIL > 0.
 *
 * Pass predicate (aoCoveragePredicate): exit 0; a report generated by THIS
 * run (generatedAt >= the spawn time; the clone ships an older report);
 * totals.total == expected (95) == results.length; totals.fail == 0; and
 * pass + honestOpen == total. HONEST-OPEN is not a failure (the tool's own
 * rule) but is counted in the record.
 */
import { spawn } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';

export interface AoReport {
  generatedAt?: string;
  totals?: { total?: number; pass?: number; honestOpen?: number; fail?: number };
  results?: Array<{ id: string; status: string; detail?: string }>;
}

export interface AoCoverageRecord {
  schema: 'ces-tester/coverage-ao@1';
  command: string;
  seed: string;
  started: string;
  ended: string;
  rc: number;
  summary_line: string | null;
  report_generated_at: string | null;
  totals: AoReport['totals'] | null;
  expected_total: number;
  not_pass: Array<{ id: string; status: string; detail: string }>;
  pass: boolean;
  reasons: string[];
}

export function aoCoveragePredicate(input: {
  rc: number;
  report: AoReport | null;
  startedAt: string;
  expectedTotal: number;
}): { pass: boolean; reasons: string[] } {
  const reasons: string[] = [];
  const r = input.report;
  if (input.rc !== 0) reasons.push(`coverage-ao exit ${input.rc}`);
  if (!r) {
    reasons.push('no coverage/ao-semantic-report.json');
    return { pass: false, reasons };
  }
  if (!r.generatedAt || r.generatedAt < input.startedAt) reasons.push(`report not from this run (generatedAt ${r.generatedAt ?? 'missing'})`);
  const t = r.totals ?? {};
  const n = r.results?.length ?? 0;
  if (t.total !== input.expectedTotal) reasons.push(`total ${t.total} (expected ${input.expectedTotal})`);
  if (n !== t.total) reasons.push(`results ${n} != total ${t.total}`);
  if (t.fail !== 0) reasons.push(`FAIL ${t.fail}`);
  if ((t.pass ?? 0) + (t.honestOpen ?? 0) !== t.total) reasons.push(`pass ${t.pass} + honest-open ${t.honestOpen} != total ${t.total}`);
  return { pass: reasons.length === 0, reasons };
}

export const AO_COVERAGE_COMMAND = 'node bin/stacksim.mjs coverage-ao';

export async function runAoCoverage(opts: {
  stacksimRoot: string;
  outFile: string;
  logBase: string;
  expectedTotal: number;
}): Promise<AoCoverageRecord> {
  const started = new Date().toISOString();
  fs.mkdirSync(path.dirname(opts.logBase), { recursive: true });
  const outFd = fs.openSync(`${opts.logBase}.out`, 'w');
  const errFd = fs.openSync(`${opts.logBase}.err`, 'w');
  const rc = await new Promise<number>((resolve) => {
    // --out keeps the report outside the stacksim clone (self-containment, V24); stdout line 1 is `report: <path>`.
    const child = spawn('node', [path.join('bin', 'stacksim.mjs'), 'coverage-ao', '--out', path.join(path.dirname(opts.outFile), 'coverage-ao')], {
      cwd: opts.stacksimRoot,
      stdio: ['ignore', outFd, errFd],
      windowsHide: true,
    });
    child.on('error', () => resolve(1));
    child.on('close', (code) => resolve(code ?? 1));
  });
  fs.closeSync(outFd);
  fs.closeSync(errFd);
  const stdout = fs.readFileSync(`${opts.logBase}.out`, 'utf8');
  const summaryLine = stdout.split(/\r?\n/).find((l) => l.startsWith('stacksim coverage-ao:')) ?? null;
  const reportLine = stdout.split(/\r?\n/).find((l) => l.startsWith('report: '));
  const reportPath = reportLine ? reportLine.slice('report: '.length).trim() : path.join(opts.stacksimRoot, 'coverage', 'ao-semantic-report.json');
  let report: AoReport | null = null;
  try {
    report = JSON.parse(fs.readFileSync(reportPath, 'utf8')) as AoReport;
  } catch {
    report = null;
  }
  const verdict = aoCoveragePredicate({ rc, report, startedAt: started, expectedTotal: opts.expectedTotal });
  const record: AoCoverageRecord = {
    schema: 'ces-tester/coverage-ao@1',
    command: AO_COVERAGE_COMMAND,
    seed: 'fresh m365_azure tenant, gcc-high-g5 seed set (the set the aoops-g5 scenario declares)',
    started,
    ended: new Date().toISOString(),
    rc,
    summary_line: summaryLine,
    report_generated_at: report?.generatedAt ?? null,
    totals: report?.totals ?? null,
    expected_total: opts.expectedTotal,
    not_pass: (report?.results ?? [])
      .filter((x) => x.status !== 'PASS')
      .map((x) => ({ id: x.id, status: x.status, detail: String(x.detail ?? '').slice(0, 300) })),
    pass: verdict.pass,
    reasons: verdict.reasons,
  };
  fs.mkdirSync(path.dirname(opts.outFile), { recursive: true });
  fs.writeFileSync(opts.outFile, JSON.stringify(record, null, 2));
  return record;
}
