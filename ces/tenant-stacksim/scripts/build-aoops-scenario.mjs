// SIMFIX / GOAL-AO-SIM-COVERAGE M1: builds scenarios/aoops-g5.json from
// scenarios/aoops-g5.config.json (the file to edit). Pure + deterministic:
// the drift guard (tests/integration/aoops-scenario.test.ts) re-runs
// buildAoopsScenario() and compares it with the committed scenario file.
import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CONFIG_PATH = path.join(ROOT, 'scenarios', 'aoops-g5.config.json');
export const SCENARIO_PATH = path.join(ROOT, 'scenarios', 'aoops-g5.json');

export function loadAoopsConfig() {
  return JSON.parse(readFileSync(CONFIG_PATH, 'utf8'));
}

export function buildAoopsScenario(config) {
  return {
    _generated: 'GENERATED by scripts/build-aoops-scenario.mjs from scenarios/aoops-g5.config.json - do not edit by hand.',
    name: config.name,
    description: config.description,
    stance: config.stance,
    seedSets: config.seedSets,
    steps: [],
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SCENARIO_PATH, JSON.stringify(buildAoopsScenario(loadAoopsConfig()), null, 2) + '\n', 'utf8');
  console.log(`wrote ${SCENARIO_PATH}`);
}
