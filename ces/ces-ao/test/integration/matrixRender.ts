// W4-AO4: renders docs/AO-95-OP-MATRIX.md from a matrix run (AO_MATRIX_WRITE=1).
import { cleanOutput, type OpObservation, type OpVerdict } from './matrixClassify.js';

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function runCell(r: OpObservation['live']): string {
  if (!r) return '—';
  const parts = [`${r.http}`, r.rowOutcome ?? r.outcome ?? '?'];
  if (r.stateChanged !== undefined) parts.push(`changed=${r.stateChanged}`);
  return parts.join(' · ');
}

export function renderMatrix(verdicts: OpVerdict[], observations: OpObservation[], meta: { run?: string; head?: string } = {}): string {
  const byId = new Map(observations.map((o) => [o.id, o]));
  const pass = verdicts.filter((v) => v.status === 'PASS').length;
  const open = verdicts.filter((v) => v.status === 'HONEST-OPEN').length;
  const failing = verdicts.length - pass - open;
  const byReq = new Map<string, number>();
  for (const v of verdicts) if (v.req) byReq.set(v.req, (byReq.get(v.req) ?? 0) + 1);

  const lines: string[] = [];
  lines.push('# AO 95-op matrix against stacksim (W4-AO4)');
  lines.push('');
  lines.push('Generated by `test/integration/ao95.matrix.stacksim.test.ts` (`AO_STACKSIM_IT=1 AO_MATRIX_WRITE=1`).');
  lines.push('Every op runs through the governed pipeline over HTTP (execute + approvals routers, principal-authenticated');
  lines.push('decisions) against an in-process stacksim `m365_azure` tenant whose record is stacksim\'s emitted tenant object');
  lines.push('as is. Each request carries its own correlationId; its evidence row is read back from the temp `ces.db` and');
  lines.push('validated against the shared AdminOps evidence schema. Sim only: `CES_AO_SIM_ONLY=1`, no `CES_AO_ALLOW_LIVE`.');
  if (meta.run) lines.push(`Run: ${meta.run}${meta.head ? ` on ces-mono ${meta.head}` : ''}.`);
  lines.push('');
  lines.push(`**PASS ${pass} · HONEST-OPEN ${open} · FAILING ${failing}** (of ${verdicts.length})`);
  lines.push('');
  lines.push('| REQ | ops |');
  lines.push('|---|---|');
  for (const [req, n] of [...byReq.entries()].sort()) lines.push(`| \`docs/requirements/${req}.md\` | ${n} |`);
  lines.push('');
  lines.push('**PASS** = the op did its job observably on the sim (read: live output carries data; write: the paired read');
  lines.push('shows the change) AND exactly one conforming evidence row per request AND every applicable deny proven.');
  lines.push('**HONEST-OPEN** = AO behaved correctly, but the sim cannot show the op working; the REQ names what is missing.');
  lines.push('');
  lines.push('| Op | Dom | Tier | Params used | Dry run | Live vs sim | Evidence row | Denies proven | Status | Reason / REQ |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const v of verdicts) {
    const o = byId.get(v.id)!;
    const rowsOk = [o.dry, o.pending, o.live, o.denySimOnly, o.denyCmmc, o.denyCui].every((r) => !r || (r.rowCount === 1 && r.conforming === 1));
    const params = [...o.params, ...o.sourced.map((s) => `${s}*`)].join(', ') || '—';
    const live = o.pending ? `202 pending → approve → ${runCell(o.live)}` : runCell(o.live);
    const reason = v.req ? `${esc(v.reason)} — \`${v.req}\`` : esc(v.reason);
    lines.push(`| ${v.id} | ${o.domain} | ${o.tier.replace('Tier ', 'T')} | ${esc(params)} | ${runCell(o.dry)} | ${esc(live)} | ${rowsOk ? 'Y' : 'N'} | ${v.denies.join(', ') || '—'} | ${v.status} | ${reason} |`);
  }
  lines.push('');
  lines.push('## Legend');
  lines.push('');
  lines.push('Params: `name*` = tenant-sourced (W4-AO2 SourceBindings), others are request inputs from `test/integration/opInputs.ts`.');
  lines.push('Dry run / Live: `HTTP · evidence outcome · changed=<stateChanged>` (write ops). Denies: `sim-only` = kind:\'live\' record refused');
  lines.push('(`denied_sim_only`); `cmmc` = L2 op on an L1 tenant (`denied_cmmc`); `cui` = bound resource outside the tenant\'s');
  lines.push('cuiBoundary (`denied_cui`; `cui(SoD first)` = Tier-3 stops at the approval gate before the boundary check);');
  lines.push('`sod` = Tier-3 pending stop + self-approval 409 + second-person approval (one rejection also proven).');
  lines.push('T2/T3 = SoD tier. HONEST-OPEN = not passing, reason + REQ recorded. REQ = requirement file for another project.');
  lines.push('');
  return lines.join('\n');
}

/** Per-REQ table of the ops it blocks, with what AO sent and what the sim did (for the REQ files). */
export function renderReqTable(req: string, verdicts: OpVerdict[], observations: OpObservation[]): string {
  const byId = new Map(observations.map((o) => [o.id, o]));
  const rows = verdicts.filter((v) => v.req === req);
  const out = ['| Op | Cmdlets / URIs AO sends (get → set) | Observed on stacksim |', '|---|---|---|'];
  for (const v of rows) {
    const o = byId.get(v.id)!;
    const cmdlets = (s: string) => [...new Set((s || '').match(/\b[A-Z][a-z]+-[A-Za-z]+\b|\baz [a-z-]+ [a-z-]+|\/v1\.0\/[A-Za-z/]+/g) ?? [])]
      .filter((c) => !/^(Select|Where|ForEach|Sort|Group|Measure|Write|Get-Date|ConvertTo|Out-Null)/.test(c))
      .slice(0, 6)
      .join(', ');
    const get = cmdlets(o.getCommand);
    const set = cmdlets(o.setCommand);
    out.push(`| ${v.id} | ${esc(get || '—')}${set ? ` → ${esc(set)}` : ''} | ${esc(v.reason)}${o.live?.pre !== undefined && o.writeShaped ? ` (pre: \`${esc(cleanOutput(o.live.pre).slice(0, 90))}\`)` : ''} |`);
  }
  return out.join('\n');
}
