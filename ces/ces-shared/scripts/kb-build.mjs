// KB-1a: merge src/data/assessor-kb/<FAMILY>.json into the two generated references:
//   src/data/assessor-approach.reference.json        (one entry per practice, 110)
//   src/data/assessor-evidence-matrix.reference.json (one entry per objective, 320)
// Order is deterministic: families in cmmc-l2-controls.reference.json `families[]` order,
// practices in `controls[]` order, objectives in assessment-objectives.reference.json order.
// Run: node scripts/kb-build.mjs   (generated files; do not hand-edit)

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_DATA = path.join(__dirname, '..', 'src', 'data');

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf-8'));

export const APPROACH_FILE = 'assessor-approach.reference.json';
export const MATRIX_FILE = 'assessor-evidence-matrix.reference.json';

/** Build both references in memory. Returns { approach, matrix } as JSON-serialisable objects. */
export function buildKb(dataDir = DEFAULT_DATA) {
  const controls = readJson(path.join(dataDir, 'cmmc-l2-controls.reference.json'));
  const objectiveOrder = readJson(path.join(dataDir, 'assessment-objectives.reference.json')).objectives.map((o) => o.objectiveId);
  const practiceOrder = controls.controls.map((c) => c.control_id);

  const byPractice = new Map();
  for (const fam of controls.families) {
    const file = path.join(dataDir, 'assessor-kb', `${fam.abbreviation}.json`);
    const kb = readJson(file);
    for (const p of kb.practices) byPractice.set(p.id, { family: fam.abbreviation, ...p });
  }

  const approachPractices = [];
  const matrixObjectives = [];
  for (const pid of practiceOrder) {
    const p = byPractice.get(pid);
    if (!p) throw new Error(`[kb-build] practice ${pid} missing from assessor-kb`);
    approachPractices.push({
      id: p.id,
      family: p.family,
      title: p.title,
      what_assessor_does: p.approach.what_assessor_does,
      common_failure_modes: p.approach.common_failure_modes,
      objectives: p.objectives.map((o) => ({ id: o.id, determination: o.determination, methods: o.methods })),
    });
  }
  const objIndex = new Map();
  for (const p of byPractice.values()) for (const o of p.objectives) objIndex.set(o.id, { practice_id: p.id, ...o });
  for (const oid of objectiveOrder) {
    const o = objIndex.get(oid);
    if (!o) throw new Error(`[kb-build] objective ${oid} missing from assessor-kb`);
    matrixObjectives.push({
      id: o.id,
      practice_id: o.practice_id,
      methods: o.methods,
      evidence: o.evidence.map((r) => ({ artifact_type: r.artifact_type, ces_source: r.ces_source, notes: r.notes })),
    });
  }

  return {
    approach: {
      _comment: 'GENERATED by scripts/kb-build.mjs from src/data/assessor-kb/<FAMILY>.json (KB-1). Do not hand-edit. Authority: NIST SP 800-171A objectives in assessment-objectives.reference.json.',
      total_practices: approachPractices.length,
      practices: approachPractices,
    },
    matrix: {
      _comment: 'GENERATED by scripts/kb-build.mjs from src/data/assessor-kb/<FAMILY>.json (KB-1). Do not hand-edit. One entry per 800-171A objective; each evidence row names the CES source that produces the artifact.',
      ces_sources: ['stack_signal', 'ao_row', 'stamper_evidence', 'ec_upload', 'eo_store', 'interview'],
      total_objectives: matrixObjectives.length,
      objectives: matrixObjectives,
    },
  };
}

export const serialize = (obj) => JSON.stringify(obj, null, 2) + '\n';

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { approach, matrix } = buildKb();
  fs.writeFileSync(path.join(DEFAULT_DATA, APPROACH_FILE), serialize(approach));
  fs.writeFileSync(path.join(DEFAULT_DATA, MATRIX_FILE), serialize(matrix));
  console.log(`[kb-build] ${approach.total_practices} practices, ${matrix.total_objectives} objectives written`);
}
