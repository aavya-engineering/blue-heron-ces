// simProvisioning.ts — synthetic-customer W5c3, founder ruling R-4: for a
// sim-only plan the headless runner stands in for the operator's "generate the
// initial password" action on the Plan tab (TCP.MU.003). It calls the same
// production generator and records only the one-time reference; the password
// value is discarded at once and never written anywhere. A live (non-sim) plan,
// or a session that already holds a reference, gets nothing.
import type { InterviewFact } from '@/shared/types/engagement';
import { PROVISIONING_NODE_IDS } from '@/features/interview/tcpProvisioningNodes';
import { generateInitialPassword, storeTouFile } from '@/features/plan/provisioningInputs';

export const HEADLESS_PROVENANCE = 'headless_runner';

export function simInitialPasswordFact(
  facts: InterviewFact[],
  tenantKind: string | null | undefined,
  slug: string,
  recordedAt: string
): InterviewFact | null {
  if (tenantKind !== 'sim') return null;
  const id = PROVISIONING_NODE_IDS.initialPassword;
  if (facts.some((f) => f.question_id === id && f.confidence !== 'unknown' && f.answer.trim() !== '')) return null;
  const { ref } = generateInitialPassword(); // the password itself is dropped here
  return {
    question_id: id,
    question_text: 'Initial password (one-time reference generated by the headless runner for a sim-only plan)',
    answer: ref,
    provenance: HEADLESS_PROVENANCE,
    confidence: 'high',
    recorded_at: recordedAt,
    source: `headless-runner:${slug}`,
  };
}

/**
 * W5c4 (P-1): for a sim-only plan the headless runner stands in for the
 * operator's terms-of-use upload (TCP.MU.002). The synthetic customer's
 * org-content already carries the PDF (operator_values_without_register_row
 * touFileName / touFileBase64); it goes through the production storeTouFile
 * (PDF checks, sha256, stored on the session), and the fact records the
 * returned `file:<name>;sha256:<hex>` reference. A live plan, org-content
 * without both values, or a session that already holds a TCP.MU.002 answer gets
 * nothing. A file storeTouFile refuses (not a PDF, too large) throws: the run
 * fails loudly rather than planning without the file it was given.
 */
export async function simTouFileFact(
  sessionId: string,
  facts: InterviewFact[],
  tenantKind: string | null | undefined,
  orgContent: unknown,
  slug: string,
  recordedAt: string
): Promise<InterviewFact | null> {
  if (tenantKind !== 'sim') return null;
  const id = PROVISIONING_NODE_IDS.touFile;
  if (facts.some((f) => f.question_id === id && f.confidence !== 'unknown' && f.answer.trim() !== '')) return null;
  const values = (orgContent as { operator_values_without_register_row?: Record<string, unknown> } | undefined)
    ?.operator_values_without_register_row;
  const name = typeof values?.touFileName === 'string' ? values.touFileName.trim() : '';
  const base64 = typeof values?.touFileBase64 === 'string' ? values.touFileBase64.trim() : '';
  if (!name || !base64) return null;
  const bin = atob(base64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  const ref = await storeTouFile(sessionId, name, bytes);
  return {
    question_id: id,
    question_text: 'Terms-of-use file (stored by the headless runner from the organisation content for a sim-only plan)',
    answer: ref,
    provenance: HEADLESS_PROVENANCE,
    confidence: 'high',
    recorded_at: recordedAt,
    source: `headless-runner:${slug}`,
  };
}
