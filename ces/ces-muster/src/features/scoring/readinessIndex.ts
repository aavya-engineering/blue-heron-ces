// readinessIndex.ts — MG-07: the static readiness index the interview reads
// without a fetch (DW#5: loadQuestionGraph never calls fetch). It is a slim,
// generated projection of three banks already copied into public/knowledge/:
//   - primed RR Question Bank.yaml        -> the 165 RR activities (the fields
//     the vendored questionSetGenerator's selection reads: id, name, levels,
//     mapped requirements, applicability), in bank order;
//   - domain Implementation Patterns.yaml -> practice, capability, actions;
//   - vendor playbook Microsoft 365.yaml  -> the fields the vendored bulk
//     cascade (bulkAnswerDerivation) reads per action.
// readinessIndex.json is the committed output; readinessIndex.test.ts rebuilds
// it from the YAML and fails when it is stale (UPDATE_READINESS_INDEX=1 rewrites it).

export interface RrActivityEntry {
  id: string;
  name: string;
  /** Where the activity sits in the bank: universal or level_specific.<L>. */
  level_group: string;
  applies_to_levels?: string[];
  mapped_requirements: string[];
  applicability?: unknown;
}

export interface SlimPattern {
  practice_id: string;
  capability: string;
  actions: Array<{ id: string; action: string; action_type: string }>;
}

export interface SlimPlaybookEntry {
  action_id: string;
  signal: string;
  m365_service: string;
  implementation?: string;
  notes?: string;
}

export interface ReadinessIndex {
  note: string;
  activities: RrActivityEntry[];
  patterns: { patterns: SlimPattern[] };
  playbook: { playbook: SlimPlaybookEntry[] };
}

/* eslint-disable @typescript-eslint/no-explicit-any -- YAML banks are untyped input */
export function buildReadinessIndex(rrBank: any, patterns: any, playbook: any): ReadinessIndex {
  const bank = rrBank?.ces?.activity_bank ?? {};
  const groups: Array<[string, any[]]> = [['universal', bank.universal?.activities ?? []]];
  for (const level of Object.keys(bank.level_specific ?? {})) {
    const acts = bank.level_specific[level]?.activities;
    if (Array.isArray(acts)) groups.push([level, acts]);
  }
  const activities: RrActivityEntry[] = [];
  for (const [level_group, acts] of groups) {
    for (const a of acts) {
      activities.push({
        id: a.id,
        name: a.name ?? a.id,
        level_group,
        ...(Array.isArray(a.applies_to_levels) ? { applies_to_levels: a.applies_to_levels } : {}),
        mapped_requirements: a.mapped_requirements ?? [],
        ...(a.applicability !== undefined ? { applicability: a.applicability } : {}),
      });
    }
  }
  return {
    note: 'GENERATED by src/features/scoring/readinessIndex.ts from public/knowledge (RR Question Bank, Implementation Patterns, M365 vendor playbook). Do not edit; run UPDATE_READINESS_INDEX=1 npx vitest run src/features/scoring/__tests__/readinessIndex.test.ts.',
    activities,
    patterns: {
      patterns: (patterns?.patterns ?? []).map((p: any) => ({
        practice_id: p.practice_id,
        capability: p.capability,
        actions: (p.actions ?? []).map((x: any) => ({ id: x.id, action: x.action, action_type: x.action_type })),
      })),
    },
    playbook: {
      playbook: (playbook?.playbook ?? []).map((e: any) => ({
        action_id: e.action_id,
        signal: e.signal,
        m365_service: e.m365_service,
        ...(e.implementation !== undefined ? { implementation: e.implementation } : {}),
        ...(e.notes !== undefined ? { notes: e.notes } : {}),
      })),
    },
  };
}
/* eslint-enable @typescript-eslint/no-explicit-any */

/** The index's activities in the RR bank shape the vendored generator extracts from. */
export function bankFromIndex(index: Pick<ReadinessIndex, 'activities'>): { ces: { activity_bank: Record<string, unknown> } } {
  const universal = index.activities.filter((a) => a.level_group === 'universal');
  const level_specific: Record<string, { activities: RrActivityEntry[] }> = {};
  for (const a of index.activities) {
    if (a.level_group === 'universal') continue;
    (level_specific[a.level_group] ??= { activities: [] }).activities.push(a);
  }
  return { ces: { activity_bank: { universal: { activities: universal }, level_specific } } };
}
